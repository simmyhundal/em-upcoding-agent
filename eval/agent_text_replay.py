"""Free replay for issue 116: what the stored agent summaries (A3.3, A3.4, A3.5: ten seeds each) would score if the two judged writing defects were refused or fixed by code.

For every submitted finding the agent's own headline and interpretation are put back into the code-built summary (the way `submit_findings` builds it), then:
  as written   the summary as the agent had it (checked against the stored summary)
  repaired     style_repair: a headline that quotes a figure the rationale never states is replaced by the code headline; an interpretation that makes the rationale repeat is dropped
  code-written the workflow's way: headline and rationale entirely from code (the agent supplies only the leaning)
Calls are identical by construction (the leaning never changes). Each version is scored by the rule judge j3.3. Free, no model. Writes docs/agent_text_replay.md.
Usage: python eval/agent_text_replay.py"""
import json
import os
import statistics as st
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import judge_rules_32 as j32  # noqa: E402
import judge_rules_33 as j33  # noqa: E402
import summary_lint as sl  # noqa: E402
import summary_rules as sr  # noqa: E402

SETS = [("A3.3", "r3a", "r3", list(range(2525, 3435, 101))), ("A3.4", "r4a", "r4", list(range(3535, 4445, 101))), ("A3.5", "r5a", "r5", list(range(4545, 5455, 101)))]
TMP = "/tmp/_agent_text"


def submitted(rid):
    last = None
    for line in open(os.path.join(ROOT, "experiments", rid, "audit.jsonl")):
        a = json.loads(line)
        if a["tool"] == "submit_findings" and '"accepted"' in a["result"]:
            last = a["args"]["findings"]
    return last or []


def replay(rid, code):
    data = os.path.join(ROOT, "data", f"synthetic_v2_{code}", f"view_{rid}")
    flagged = os.path.join(ROOT, "experiments", code, "flagged.csv")
    packet_of = j32.packets(data, flagged, True)
    stored = {json.loads(x)["provider_id"]: json.loads(x) for x in open(os.path.join(ROOT, "experiments", rid, "case_summaries_checked.jsonl")) if x.strip()}
    os.makedirs(TMP, exist_ok=True)
    variants = {"as written": [], "repaired": [], "code-written": []}
    same = defects = 0
    info = []
    for f in submitted(rid):
        pid, lean = f["provider_id"], f["leaning"]
        if pid not in stored:
            continue
        packet = packet_of(pid)
        written = sr.assemble(packet, lean, f.get("headline"), f.get("interpretation"), version="2.1")
        mine = stored[pid]["summary"]                            # the summary as the agent actually had it: defects are read from this, not from the rebuild
        same += int(written["headline"] == mine["headline"] and written["rationale"] == mine["rationale"])
        d = sl.style_defects(mine)
        defects += bool(d)
        info.append({"lean": lean, "defects": d})
        repaired = sl.style_repair(written, packet, f.get("headline"), f.get("interpretation")) if d else mine      # untouched where it has no defect
        for name, summ in (("as written", mine), ("repaired", repaired), ("code-written", sr.assemble(packet, lean, version="2.1"))):
            assert summ["leaning"] == lean
            variants[name].append({**stored[pid], "summary": summ})
    out = {}
    for name, recs in variants.items():
        path = os.path.join(TMP, f"{rid}_{name.replace(' ', '_')}.jsonl")
        with open(path, "w") as fh:
            fh.writelines(json.dumps(r) + "\n" for r in recs)
        rows = j33.run(data, flagged, path, os.path.join(TMP, "out.jsonl"), run_dir=os.path.join(ROOT, "experiments", rid))
        out[name] = [r["score"] for r in rows]
    return {"n": len(info), "same": same, "defects": defects, "info": info, "scores": out}


def main():
    L = ["# Agent text replay: what code-checked wording would do to the rule-judge score (issue 116)", "", "[Back to the README](../README.md) · [v4/v5 plan](v4_v5_plan.md)", "",
         "Generated by `python eval/agent_text_replay.py`. **Free:** the stored findings of the agent runs replayed, no model. The two defects are the ones the rule judge j3.3 deducts for in agent text: a headline figure the rationale never "
         "states, and a repeated sentence (`summary_lint.style_defects`). **Calls are identical in every version** (the leaning is never changed). The judge is the project's own and no person has checked it: this is wording quality, not evidence quality.", "",
         "| Agent | Findings | Rebuilt from the agent's text equals stored | With a style defect (would be refused) | Of upcoding calls | j3.3 as written | j3.3 repaired | j3.3 code-written |", "|---|---|---|---|---|---|---|---|"]
    tot = {"as written": [], "repaired": [], "code-written": []}
    for arm, pre, code_pre, seeds in SETS:
        agg = {"n": 0, "same": 0, "defects": 0, "up": 0, "up_def": 0, "scores": {k: [] for k in tot}}
        for s in seeds:
            r = replay(f"{pre}_{s}", f"{code_pre}_{s}")
            agg["n"] += r["n"]
            agg["same"] += r["same"]
            agg["defects"] += r["defects"]
            agg["up"] += sum(i["lean"] == sr.UPCODING for i in r["info"])
            agg["up_def"] += sum(i["lean"] == sr.UPCODING and bool(i["defects"]) for i in r["info"])
            for k in tot:
                agg["scores"][k] += r["scores"][k]
                tot[k] += r["scores"][k]
        L.append(f"| {arm} | {agg['n']} | {agg['same']} | {agg['defects']} ({agg['defects'] / max(agg['n'], 1):.0%}) | {agg['up_def']} of {agg['up']} ({agg['up_def'] / max(agg['up'], 1):.0%}) | "
                 + " | ".join(f"{st.mean(agg['scores'][k]):.2f}" for k in ("as written", "repaired", "code-written")) + " |")
    L += ["", "For reference, the workflow's code-written summaries score about 4.9 on the same judge (docs/judge_unjudged.md).", "",
          "## Reading", "",
          "- A hard refusal of the two defects would stop a large share of the agent's findings (column 4): each refusal costs the agent a rewrite turn, so the cheaper and surer fix is for code to write the headline and drop a repeating interpretation (`repaired`).",
          "- `code-written` is the workflow's way and the ceiling on these two checks; the gap to `repaired` is whatever the agent's own interpretation still costs.",
          "- **Decision for agent v5.0:** repair by code, do not refuse. `submit_findings` keeps the agent's leaning and, where the headline or interpretation has one of the two defects, code writes the headline and drops the repeating interpretation (`summary_lint.style_repair`), "
          "so the agent never spends a turn on wording and the calls cannot change. Expected rule-judge mean for the agent: about 4.8 to 4.9 (`repaired`), against 4.5 to 4.7 as written. The change is wording only, so no paid run is needed to adopt it; repeat the judge on the first v5.0 run. "
          "Wiring into `submit_findings` happens when agent v5.0 is built (#128); the function and its tests are in `src/summary_lint.py` and `tests/test_summary_lint_style.py`."]
    open(os.path.join(ROOT, "docs", "agent_text_replay.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
