"""Downstream check of candidate screens (issue 127): the FROZEN workflow v2.3 pipeline (API-free: no_model) run on the top-10% list of each screen, on the data 4.0 development seeds,
scored with score 4.0. The rules and policy are the frozen ones (fitted on data 2.2), so this measures what the list contributes under today's rules, not what a v4.0 workflow could do.
Free. Writes docs/screens_v4_pipeline.md. Usage: python eval/screens_v4_pipeline.py"""
import multiprocessing as mp
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import dev_release3 as dev  # noqa: E402
import make_d4_dev as md  # noqa: E402
import make_v2_office_workflow_runs as ow  # noqa: E402
import run_release2 as r2  # noqa: E402
import score_40 as s4  # noqa: E402

METHODS = ["eb_ratio_t", "eb_upper_c", "eb_upper_t", "pay_resid", "hi_no_test"]
DOC = os.path.join(ROOT, "docs", "screens_v4_pipeline.md")


def work(job):
    method, seed = job
    code = f"d4_{seed}"
    name = dev.write_flagged(code, method, 10)
    rid = f"d4s_{method}_{seed}"
    if not r2.done(rid, "case_summaries_checked.jsonl"):
        ow.run(rid, code, name, f"frozen workflow v2.3 (API-free) on the {method} top-10% list, data 4.0 development seed {seed}", version="2.3", tier1_n=11, no_model=True)
    c = s4.from_run(rid, code)
    return method, seed, {k: c[k] for k in ("recovered", "staff_cost", "abrasion", "score", "found", "upcoders", "demands", "honest_called", "rounds")}


def main():
    jobs = [(m, s) for m in METHODS for s in md.SEEDS]
    with mp.get_context("spawn").Pool(4) as pool:
        res = pool.map(work, jobs, chunksize=1)
    L = ["# Frozen workflow v2.3 on each screen's top-10% list, data 4.0 development seeds (issue 127)", "", "[Back to the README](../README.md) · [screens on data 4.0](screens_v4.md)", "",
         "Generated by `python eval/screens_v4_pipeline.py`. Free (API-free workflow). The pipeline, rules 2.3 and policy are the frozen ones fitted on data 2.2: they decide only where the 99215 signals "
         "or the chart rule speak, so this is what each list is worth **under today's rules**. Score 4.0 per seed, 11 development seeds.", "",
         "| Screen | Upcoders found (of 88) | Honest called | Recovered | Staff-hours cost | Abrasion | **Score 4.0 per seed** |", "|---|---|---|---|---|---|---|"]
    n = len(md.SEEDS)
    for m in METHODS:
        rows = [r for mm, s, r in res if mm == m]
        t = {k: sum(r[k] for r in rows) for k in rows[0]}
        L.append(f"| {m} | {t['found']} | {t['honest_called']} | ${t['recovered'] / n:,.0f} | ${t['staff_cost'] / n:,.0f} | ${t['abrasion'] / n:,.0f} | **${t['score'] / n:,.0f}** |")
    open(DOC, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
