"""Grade the data-quality pre-flight against the defects injected into data 2.2 (issue 81). Free. Uses the answer key (evaluation only).

Runs `src/data_quality.py` on a clean data 2.2 dataset (nothing should be flagged beyond information) and on the dataset with injected defects
(every injected defect should be found), and writes docs/data_quality.md.

Usage:
    python eval/grade_data_quality.py [--write]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
import data_quality as dq  # noqa: E402

CLEAN = [("261015_1_code", "seed 42, data 2.1 (no control totals, no group billing)"),
         ("261016_1_code", "seed 42, data 2.2 default settings (honest noise, group billing, corrections)"),
         ("261015_66_code", "seed 1414, data 2.1, 600 doctors")]
DEFECT = "261016_2_code"


def prf(found, truth):
    found, truth = set(found), set(truth)
    tp = len(found & truth)
    return tp, len(found), len(truth)


def grade_defects():
    d = os.path.join(ROOT, "data", f"synthetic_v2_{DEFECT}")
    key = json.load(open(os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_{DEFECT}.json")))
    inj = key["defects"]
    t = dq.load(d)
    rep = dq.run_checks(d)
    by = {c["id"]: c for c in rep["checks"]}
    rows = []
    # duplicates: the copies the check names against the injected copies
    _, dups = dq.check_duplicates(t)
    tp, nf, nt = prf([x[0] for x in dups], [p[0] for p in inj["duplicates"]["pairs"]])
    rows.append(("Duplicate claims", f"{nt:,} copies injected", f"{nf:,} flagged, {tp:,} of them injected", f"precision {tp / nf:.1%}, recall {tp / nt:.1%}", by["duplicates"]["status"]))
    # orphan chains
    ids = {h["claim_id"] for h in t["headers"]}
    found = [h["claim_id"] for h in t["headers"] if h["claim_frequency"] in ("7", "8") and h["original_claim_id"] not in ids]
    inj_o = inj["orphans"]["replacements"] + inj["orphans"]["voids"]
    tp, nf, nt = prf(found, inj_o)
    rows.append(("Orphan replacements and voids", f"{nt:,} injected", f"{nf:,} flagged, {tp:,} injected", f"precision {tp / nf:.1%}, recall {tp / nt:.1%}", by["chains"]["status"]))
    # unknown members
    found = [h["claim_id"] for h in t["headers"] if h["member_id"] not in t["members"]]
    tp, nf, nt = prf(found, inj["unknown_member"]["claim_ids"])
    rows.append(("Member ids not in eligibility", f"{nt:,} injected", f"{nf:,} flagged", f"precision {tp / nf:.1%}, recall {tp / nt:.1%}", by["member_join"]["status"]))
    # rendering missing under an organizational biller
    att = dq.attribution(t)
    found = [h["claim_id"] for h, a in zip(t["headers"], att) if a[2] and a[3]]
    tp, nf, nt = prf(found, inj["no_rendering"]["claim_ids"])
    rows.append(("Blank rendering NPI under a group biller", f"{nt:,} injected", f"{nf:,} flagged", f"precision {tp / nf:.1%}, recall {tp / nt:.1%}", by["rendering_npi"]["status"]))
    # diagnosis cap
    cap = inj["dx_truncation"]
    susp = by["dx_per_claim"]["numbers"]["suspected_cap_months"]
    months_true = {f"2024-{m:02d}" for m in cap["months"]}
    tp, nf, nt = prf(susp, months_true)
    caps = sorted({v["cap"] for v in susp.values()})
    rows.append(("Diagnosis cap", f"cap {cap['cap']} in months {cap['months'][0]} to {cap['months'][-1]}", f"months flagged: {nf}, cap read as {caps}", f"{tp} of {nt} months found, {nf - tp} false", by["dx_per_claim"]["status"]))
    # control totals
    mm = by["control_totals"]["numbers"]["months_mismatched"]
    expected_delta = len(inj["duplicates"]["pairs"]) - len(inj["orphans"]["missing_originals"])
    got_delta = sum(v["claims_diff"] for v in mm.values())
    rows.append(("Control totals", f"net {expected_delta:+,} claims injected", f"{len(mm)} of 12 months differ, net {got_delta:+,} claims", "net difference equals the injected rows" if got_delta == expected_delta else "MISMATCH", by["control_totals"]["status"]))
    return rep, rows


def grade_clean():
    out = []
    for rid, label in CLEAN:
        rep = dq.run_checks(os.path.join(ROOT, "data", f"synthetic_v2_{rid}"))
        warns = [c["id"] for c in rep["checks"] if c["status"] in ("warn", "block")]
        out.append((rid, label, rep["status"], ", ".join(warns) or "none", rep["checks"][5]["numbers"]["rate"]))
    return out


def report():
    rep, rows = grade_defects()
    clean = grade_clean()
    c = ["| Defect | Injected | Found | Agreement | Check status |", "|---|---|---|---|---|"]
    c += [f"| {a} | {b} | {x} | {y} | {z} |" for a, b, x, y, z in rows]
    k = ["| Dataset | Description | Overall status | Checks with a warning | Natural duplicate rate |", "|---|---|---|---|---|"]
    k += [f"| `{a}` | {b} | {s} | {w} | {r:.2%} |" for a, b, s, w, r in clean]
    return ("# Data-quality pre-flight (issue 81)\n\n[Back to the README](../README.md)\n\n"
            "Generated by `python eval/grade_data_quality.py --write`. The pre-flight (`src/data_quality.py`) runs once per data load, before any screen, on the delivered plan tables; "
            "it never reads an answer key. This page grades it against the defects injected into data 2.2 ([data_v2_2.md](data_v2_2.md), issue 80).\n\n"
            "## What it checks\n\n"
            "| Check | Warns when | Blocks when |\n|---|---|---|\n"
            "| Control totals | a month's claims or paid dollars differ from the plan's control totals by more than 0.1% | more than 5% in any month |\n"
            "| E/M mix | total variation distance from the Family Practice benchmark above 0.15 (informational) | never |\n"
            "| Diagnosis codes per claim | a month's maximum is below the extract's width of 6 and 15% or more of its claims sit at that maximum (suspected truncation) | never |\n"
            "| Rendering NPI | blanks under an organizational biller exceed 0.5% of claims (single-clinician blanks fall back to billing and are only reported) | above 20% |\n"
            "| Member join | below 99.9% join to eligibility | below 90% |\n"
            "| Duplicates | more than 0.4% of paid claims repeat another claim's member, date, biller, diagnoses and E/M line | never |\n"
            "| Replacement and void chains | any replacement or void whose original is missing | never |\n"
            "| Immature recent months | a latest month holds under 70% of a typical earlier month | never |\n\n"
            "A warning does not stop the run; a block does (workflow: `flagging.py --preflight` exits non-zero unless told to continue). "
            "Thresholds were set by looking at the clean datasets below, not the defect dataset: the natural duplicate rate in clean synthetic data is about 0.1%, "
            "so the duplicate threshold sits at 0.4%.\n\n"
            "## Graded on injected defects\n\n"
            f"Dataset `{DEFECT}`: seed 42, data 2.2 with duplicates 1%, orphans 30%, unknown members 0.5%, blank rendering NPI 3% of group-billed claims and a diagnosis cap of 3 from July.\n\n"
            + "\n".join(c) + "\n\n"
            "## Nothing flagged on clean data\n\n" + "\n".join(k) + "\n\n"
            "Control totals are only available on data 2.2 builds that write them (`not_available` is not a warning). The E/M mix is informational: the synthetic mix is "
            "10 to 12% (total variation) from the Family Practice benchmark on 216 doctors, within its threshold, and a real plan would see far larger gaps by specialty mix.\n\n"
            "## How findings are held\n\n"
            "Per-provider flags carry the sentence a reviewer reads next to a finding (for example \"38% of the claims billed by this provider's group lacked a rendering NPI\"). "
            "`data_quality.hold_decision` turns them into a policy: an affected provider's upcoding finding needs chart evidence (at least 8 charts received), "
            "otherwise it is held, and every affected finding carries the data caveat and is marked low confidence. Truncation-suspect months affect any provider with "
            "25% or more of its claims in those months. **Workflow:** `src/flagging.py --preflight V2_DIR` writes the report next to the flagged list and adds a "
            "`data_quality` column. **Agent v3.2:** the read-only `data_quality` tool returns the global flags and, for a provider, its flags; `flag_data_issue` records a "
            "concern for a person to raise with the plan and can hold findings; `submit_findings` refuses an upcoding leaning for a held provider without chart evidence. "
            "Neither stream requests data from the plan.\n\n"
            "## Limits\n\n"
            "- Graded on one injected dataset and three clean ones, all synthetic and all seed 42 or 1414; thresholds were not tuned on the defect dataset but the defects "
            "were chosen to be detectable in kind. A real extract has defects nobody has listed.\n"
            "- The duplicate check can only see exact repeats; a real double load with a changed field would pass. Truncation is detected only when the cap sits below the extract's width "
            "and affects a visible share of claims, and a cap applied to every month is flagged on its own pile-up (no month to compare against).\n"
            "- The claims-lag check is a volume ratio; it is not tested against a real lag (issue 78 is not built).\n"
            "- The agent's hold policy is built and unit tested offline; no model run used it, so how an agent uses these tools is untested.\n")


if __name__ == "__main__":
    t = report()
    print(t)
    if "--write" in sys.argv:
        open(os.path.join(ROOT, "docs", "data_quality.md"), "w").write(t)
