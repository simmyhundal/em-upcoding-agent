"""Release 4: all arms on the 20 development seeds, with the reward used to train the learned policy as one summary number. Free (stored runs and development tables).

Score(lambda) = upcoders found - honest doctors called - lambda x rounds sent to honest practices (rounds = chart requests, follow-ups and audit-trail requests). Reported per set of ten
seeds (the release 2 seeds 1515 to 2424 and the release 3 seeds 2525 to 3434) so each agent run is compared with the workflows on the same seeds, as a total and per seed, at lambda
0.02, 0.05 and 0.1, beside the three components. The learned variants L and GL are the leave-seeds-out cross-validated choices of docs/rl_escalate_policy.md (lambda 0.05), not the
in-sample fit. A3.4 has no development runs yet (paid).

Usage: python eval/dev_arm_scores.py     (writes docs/dev_arm_scores.md)
"""
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import dev_release4 as dev4  # noqa: E402
import rl_escalate_policy as r2  # noqa: E402

SETS = {"r2": ("release 2 seeds (1515 to 2424)", [s for c, s in dev4.SEEDS if c == "r2"]), "r3": ("release 3 seeds (2525 to 3434)", [s for c, s in dev4.SEEDS if c == "r3"])}
LAMS = (0.02, 0.05, 0.1)


def stored_run(rid, code, seed):
    key = json.load(open(os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_{code}_{seed}.json")))["providers"]
    called = {x["provider_id"] for x in map(json.loads, open(os.path.join(ROOT, "experiments", rid, "case_summaries_checked.jsonl")))
              if x["summary"]["leaning"] == "pattern_consistent_with_upcoding"}
    rounds = 0
    for line in open(os.path.join(ROOT, "experiments", rid, "office_transcript.jsonl")):
        e = json.loads(line)
        if e.get("action") in ("send_request", "follow_up", "audit_trail") and "error" not in e and key[e["provider_id"]]["role"] != "upcoder":
            rounds += 1
    up = {p for p, v in key.items() if v["role"] == "upcoder"}
    return {"found": len(called & up), "honest_called": len(called - up), "rounds": rounds}


def agg(parts):
    return {k: sum(p[k] for p in parts) for k in ("found", "honest_called", "rounds")}


def learned_rows(res_rows, P, honest, lam, gate):
    out = {"r2": [], "r3": []}
    for i, r in enumerate(res_rows):
        sc = {b: P[b]["found"][i] - 1.0 * P[b]["hc"][i] - lam * honest[i] * P[b]["extra"][i] for b in r2.BRANCHES}
        b = max(sc, key=sc.get)
        skip = gate is not None and r["rank"] > dev4.TIER1_N and r["ratio"] < gate
        out[r["set"]].append({"found": 0 if skip else int(r[b]["found"]), "honest_called": 0 if skip else int(r[b]["honest_called"]),
                              "rounds": 0 if (skip or r["upcoder"]) else r[b]["rounds"], "seed": r["seed"]})
    return out


def main():
    d4 = json.load(open(os.path.join(ROOT, "experiments", "d4_dev_results.json")))
    rows = json.load(open(r2.DATA))
    P, honest = r2.cv_predict(rows)
    L = learned_rows(rows, P, honest, 0.05, None)
    GL = learned_rows(rows, P, honest, 0.05, 2.5)
    L_out = ["# Release 4: every arm on the development seeds, with the learned-policy reward as one summary number", "", "[Back to the README](../README.md)", "",
             "Generated by `python eval/dev_arm_scores.py`. Free. **Score(lambda) = upcoders found - honest doctors called - lambda x rounds sent to honest practices.** "
             "Higher is better; lambda is the price of one request round to an honest practice. The three components are shown beside it because the score depends on lambda. "
             "L and GL are the leave-seeds-out cross-validated choices of the learned policy (lambda 0.05), not the in-sample fit. Workflow variants and the agent run on the same ten seeds in each table. "
             "**A3.4 has not been run on development seeds** (paid; about $0.2 a seed).", ""]
    for key, (title, seeds) in SETS.items():
        arms = {}
        pre = "r2" if key == "r2" else "r3"
        arms["W2.2"] = agg([stored_run(("r2w_" if key == "r2" else "r3w2_") + str(s), f"{pre}", s) for s in seeds])
        for name, tag in (("W2.3", "B"), ("G (gate 2.5)", "T2.5")):
            xs = [r for r in d4 if r["config"] == tag and r["set"] == key]
            arms[name] = {"found": sum(r["found"] for r in xs), "honest_called": sum(r["honest_called"] for r in xs), "rounds": sum(r["rounds_honest"] for r in xs)}
        arms["L (learned, CV)"] = agg(L[key])
        arms["GL (gate and learned, CV)"] = agg(GL[key])
        arms["A3.2" if key == "r2" else "A3.3"] = agg([stored_run(("r2a_" if key == "r2" else "r3a_") + str(s), pre, s) for s in seeds])
        total_up = sum(r["upcoders"] for r in d4 if r["config"] == "B" and r["set"] == key)
        L_out += [f"## {title}: {total_up} planted upcoders", "", "| Arm | Upcoders found | Honest doctors called | Rounds to honest practices | " + " | ".join(f"Score ({l:g}) per seed" for l in LAMS) + " |",
                  "|---|---|---|---|" + "---|" * len(LAMS)]
        for name, a in arms.items():
            sc = [(a["found"] - a["honest_called"] - l * a["rounds"]) / len(seeds) for l in LAMS]
            L_out.append(f"| {name} | {a['found']} | {a['honest_called']} | {a['rounds']} | " + " | ".join(f"{x:.2f}" for x in sc) + " |")
        L_out.append("")
        best = {l: max(arms, key=lambda n: arms[n]["found"] - arms[n]["honest_called"] - l * arms[n]["rounds"]) for l in LAMS}
        L_out += [f"Best arm at each price: " + ", ".join(f"lambda {l:g}: {best[l]}" for l in LAMS) + ".", ""]
    # release 1: the arms of the issue 61 evaluation (data 2.0 and 2.1, ten seeds 404 to 1313, 80 upcoders), same score from their office transcripts and answer keys
    import analyze_eval61 as a61
    res = a61.load()
    keys = sorted({k for k, _ in res if "_r" not in k}, key=lambda k: int(k[1:]))
    arms = {}
    for arm in a61.ARMS:
        parts = []
        for k in keys:
            r = res[(k, arm)]
            ans = json.load(open(os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_{r['code']}.json")))["providers"]
            rounds = 0
            for line in open(os.path.join(ROOT, "experiments", r["run"], "office_transcript.jsonl")):
                e = json.loads(line)
                if e.get("action") in ("send_request", "follow_up", "audit_trail") and "error" not in e and ans[e["provider_id"]]["role"] != "upcoder":
                    rounds += 1
            parts.append({"found": r["found"], "honest_called": r["accused"], "rounds": rounds})
        arms[{"W2.0": "W2.0 (data 2.0)", "W2.1": "W2.1 (data 2.1)", "A3.0": "A3.0 (data 2.0)", "A3.1": "A3.1 (data 2.1)"}[arm]] = agg(parts)
    L_out += [f"## Release 1 seeds (404 to 1313, the issue 61 evaluation on data 2.0 and 2.1): 80 planted upcoders", "",
              "Different data (honest doctors bill exactly the justified level, no coding noise), different seeds and different screens, so **do not compare these rows with the two tables above**; "
              "they are here for the history of the score.", "",
              "| Arm | Upcoders found | Honest doctors called | Rounds to honest practices | " + " | ".join(f"Score ({l:g}) per seed" for l in LAMS) + " |", "|---|---|---|---|" + "---|" * len(LAMS)]
    for name, a in arms.items():
        sc = [(a["found"] - a["honest_called"] - l * a["rounds"]) / len(keys) for l in LAMS]
        L_out.append(f"| {name} | {a['found']} | {a['honest_called']} | {a['rounds']} | " + " | ".join(f"{x:.2f}" for x in sc) + " |")
    best = {l: max(arms, key=lambda n: arms[n]["found"] - arms[n]["honest_called"] - l * arms[n]["rounds"]) for l in LAMS}
    L_out += ["", "Best arm at each price: " + ", ".join(f"lambda {l:g}: {best[l]}" for l in LAMS) + ".", ""]
    L_out += ["## Is this score an appropriate way to compare the arms?", "",
              "- **As one summary number, yes, with care.** It turns the project's three concerns (upcoders found, honest doctors flagged, burden on honest practices) into one figure, "
              "and it is exactly what the learned policy was trained to maximize. It is not a replacement for the components or the thresholds (recall, precision, honest practices asked).",
              "- **It depends on lambda,** a price we chose. Read it at several values (0.02, 0.05, 0.1 above); an arm that wins at all of them is better on any reasonable price, one that wins at one is a trade-off.",
              "- **It favors what it trained.** L and GL are fitted to this reward, so their scores here are only fair when cross-validated (as shown) and only trustworthy on the fresh seeds. "
              "The agent and the hand-set workflows were never optimized for it; part of any gap is simply that.",
              "- **It leaves out things that matter:** dollars at stake (a missed large upcoder counts the same as a small one), summary quality (judge scores), cost in dollars, and recall as a share of all upcoders. "
              "Those stay as separate columns in the results.",
              "- **Free replays count a case the model would have answered as inconclusive,** so a workflow's found count can differ by one from its recorded run (W2.3 on the release 3 seeds: 36 here, 37 recorded).",
              "- **Different seeds, different agents:** the agent arms ran only on the seeds of their release, so each table compares the agent with the workflows on the same ten seeds; do not read across the tables.",
              "- The pre-registered fresh test keeps its own primary criteria (#108); the score is a development summary."]
    open(os.path.join(ROOT, "docs", "dev_arm_scores.md"), "w").write("\n".join(L_out) + "\n")
    print("\n".join(L_out))


if __name__ == "__main__":
    main()
