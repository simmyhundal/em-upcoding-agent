FWA_KINDS = md.FWA


def oracle_job(seed):
    return seed, md.oracle(f"d42_{seed}")


def run_detail(arm, seed):
    """Per-run detail the metrics do not carry: who was listed, asked and called, by kind of truth, and what the office answered to phantom claims."""
    rid = f"d42wl{ref.ARMS[arm].lower()}_{seed}"
    code = f"d42_{seed}"
    claims, key, truth = dt.context(code)
    i = s4.run_inputs(rid, code)
    listed, asked, called = md.listed_ids(rid), set(i["rounds"]), i["called"]
    P = key["providers"]
    cost = dt.pursuit_cost()
    d = Counter()
    for pid, v in P.items():
        net = truth[pid]["net_rate"]
        lvl = max(v["true_overpay_level_net"], 0)
        fw = v["true_overpay_fwa"]
        feats = {"rate>=15%": net >= 0.15, "habit": v["habit"] is not None, "justified(m=1)": v["true_overpay_total"] >= cost}
        for k in FWA_KINDS:
            feats[k] = v["intent"][k]
        feats["any FWA"] = any(v["intent"][k] for k in FWA_KINDS)
        feats["justified, level dollars only"] = lvl >= cost
        feats["justified only through FWA"] = v["true_overpay_total"] >= cost and lvl < cost
        for f, on in feats.items():
            if on:
                d[(f, "providers")] += 1
                d[(f, "listed")] += pid in listed
                d[(f, "asked")] += pid in asked
                d[(f, "called")] += pid in called
    nr = Counter()
    for line in open(os.path.join(ROOT, "experiments", rid, "office_transcript.jsonl")):
        e = json.loads(line)
        for df in e.get("deficiencies", []):
            if df["code"] == "NO_RECORD":
                nr["responses"] += 1
                nr["claims"] += len(df["claim_ids"])
    return d, nr


