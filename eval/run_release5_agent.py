import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import judge_agent_runs as jar  # noqa: E402
import run_agent  # noqa: E402
import run_release2 as r2  # noqa: E402

if __name__ == "__main__":
    from dotenv import load_dotenv
    load_dotenv(os.path.join(ROOT, ".env"))
    seed = int(sys.argv[1])
    code, rid = f"r5_{seed}", f"r5a_{seed}"
    if not r2.done(rid, "results.json"):
        run_agent.main(rid, code, version="3.5", effort="low", screen_method="eb_ratio_t", top_pct=10, records_budget=run_agent.EVAL_RECORDS_BUDGET_33)
    if not os.path.isdir(os.path.join(ROOT, "data", f"synthetic_v2_{code}", f"view_{rid}")):
        jar.main(rid, code, "3.5")
    out = {**r2.score(rid, code), "effort": "low", "model": "claude-opus-5-5"}
    json.dump(out, open(os.path.join(ROOT, "experiments", f"r5a_results_{seed}.json"), "w"), indent=1)
    print(json.dumps(out))
