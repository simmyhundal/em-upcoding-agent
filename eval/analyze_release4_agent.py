"""Release 4, Phase B analysis (issue 108), as posted before the paid run. Free (stored runs).

Per seed, score = upcoders found - honest doctors flagged - 0.05 x rounds sent to honest practices (request rounds, follow-ups and audit-trail requests). The agent's gap is its mean
score minus workflow v2.3's on the same seeds: A3.4 on the fresh seeds 3535 to 4444 (against the Phase A W23 runs), A3.3 on the release 3 seeds 2525 to 3434 (against its stored v2.3
runs). The two sets of seeds differ, so the comparison of gaps is UNPAIRED and descriptive (a bootstrap interval over each set's seeds). "The advisor helps" is read as: A3.4's
gap is larger than A3.3's AND A3.4 flags no more than one extra honest doctor in total than W2.3 on the same seeds (our reading of the posted wording).

Usage: python eval/analyze_release4_agent.py [--write]       (writes docs/release4_agent_results.md)
"""
import json
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import dev_arm_scores as das  # noqa: E402
from analyze_release2 import cost  # noqa: E402

LAM = 0.05
FRESH = [3535, 3636, 3737, 3838, 3939, 4040, 4141, 4242, 4343, 4444]
R3 = [2525, 2626, 2727, 2828, 2929, 3030, 3131, 3232, 3333, 3434]


def seed_row(rid, code, seed):
    r = das.stored_run(rid, code, seed)
    r["score"] = r["found"] - r["honest_called"] - LAM * r["rounds"]
    r["cost"] = cost(rid)
    return r


def mean(xs):
    return sum(xs) / len(xs)


def boot_diff(a, b, n=10000, seed=1044):
    rng = random.Random(seed)
    d = sorted(mean([rng.choice(a) for _ in a]) - mean([rng.choice(b) for _ in b]) for _ in range(n))
    return mean(a) - mean(b), d[int(0.025 * n)], d[int(0.975 * n) - 1]


def main():
    arms = {"A3.4 (fresh seeds)": [seed_row(f"r4a_{s}", "r4", s) for s in FRESH], "W2.3 (fresh seeds)": [seed_row(f"r4w23_{s}", "r4", s) for s in FRESH],
            "G": [seed_row(f"r4g_{s}", "r4", s) for s in FRESH], "L": [seed_row(f"r4l_{s}", "r4", s) for s in FRESH], "GL (v2.4 default)": [seed_row(f"r4gl_{s}", "r4", s) for s in FRESH],
            "A3.3 (release 3 seeds)": [seed_row(f"r3a_{s}", "r3", s) for s in R3], "W2.3 (release 3 seeds)": [seed_row(f"r3w_{s}", "r3", s) for s in R3]}
    L = ["# Release 4, Phase B: agent v3.4 on the fresh seeds (issue 108)", "", "[Back to the README](../README.md)", "",
         "Generated by `python eval/analyze_release4_agent.py`. Free; the paid runs were agent v3.4 on seeds 3535 to 4444 (Opus 5.5, low effort). Score per seed = upcoders found - honest doctors flagged "
         f"- {LAM} x rounds sent to honest practices. **The comparison with A3.3 is unpaired (different seeds) and descriptive.**", "",
         "| Arm | Upcoders found | Honest doctors flagged | Rounds to honest practices | Mean score per seed | Cost |", "|---|---|---|---|---|---|"]
    for name, rows in arms.items():
        L.append(f"| {name} | {sum(r['found'] for r in rows)} | {sum(r['honest_called'] for r in rows)} | {sum(r['rounds'] for r in rows)} | {mean([r['score'] for r in rows]):.2f} | ${sum(r['cost'] for r in rows):.2f} |")
    g34 = [a["score"] - w["score"] for a, w in zip(arms["A3.4 (fresh seeds)"], arms["W2.3 (fresh seeds)"])]
    g33 = [a["score"] - w["score"] for a, w in zip(arms["A3.3 (release 3 seeds)"], arms["W2.3 (release 3 seeds)"])]
    d, lo, hi = boot_diff(g34, g33)
    extra = sum(r["honest_called"] for r in arms["A3.4 (fresh seeds)"]) - sum(r["honest_called"] for r in arms["W2.3 (fresh seeds)"])
    gl = [a["score"] - w["score"] for a, w in zip(arms["A3.4 (fresh seeds)"], arms["GL (v2.4 default)"])]
    helps = d > 0 and extra <= 1
    tools = {}
    for sd in FRESH:
        for line in open(os.path.join(ROOT, "experiments", f"r4a_{sd}", "audit.jsonl")):
            t = json.loads(line)["tool"]
            tools[t] = tools.get(t, 0) + 1
    L += ["", f"**Gap to W2.3 (mean score per seed):** A3.4 on the fresh seeds {mean(g34):+.2f}; A3.3 on the release 3 seeds {mean(g33):+.2f}. Difference of gaps {d:+.2f} (95% bootstrap interval {lo:+.2f} to {hi:+.2f}, unpaired).",
          f"**Extra honest doctors flagged by A3.4 over W2.3 on the same seeds:** {extra:+d}.",
          f"**By the posted reading, the advisor {'meets the criterion' if helps else 'does not meet the criterion'}** (larger gap: {'yes' if d > 0 else 'no'}; at most one extra honest doctor: {'yes' if extra <= 1 else 'no'}). "
          + (f"**But the difference of gaps is {d:+.2f} with an interval from {lo:+.2f} to {hi:+.2f}, so it is not distinguishable from no difference: no evidence of a benefit.**" if lo <= 0 <= hi else ""),
          f"Tool use by A3.4 over the ten runs: advise_next_step {tools.get('advise_next_step', 0)} calls, hybrid_review {tools.get('hybrid_review', 0)}, request_records {tools.get('request_records', 0)}, follow_up_records {tools.get('follow_up_records', 0)}, request_audit_trail {tools.get('request_audit_trail', 0)}.",
          f"A3.4 minus the v2.4 default GL on the same seeds: {mean(gl):+.2f} per seed (descriptive).", "",
          "## Per seed (A3.4 found / honest flagged / rounds to honest)", "", "| Seed | A3.4 | W2.3 | GL |", "|---|---|---|---|"]
    for i, s in enumerate(FRESH):
        a, w, g = arms["A3.4 (fresh seeds)"][i], arms["W2.3 (fresh seeds)"][i], arms["GL (v2.4 default)"][i]
        L.append(f"| {s} | {a['found']} / {a['honest_called']} / {a['rounds']} | {w['found']} / {w['honest_called']} / {w['rounds']} | {g['found']} / {g['honest_called']} / {g['rounds']} |")
    L += ["", f"**The agent never called the advisor ({tools.get('advise_next_step', 0)} calls in ten runs), so none of the difference can be attributed to it.** What A3.4 adds over A3.3 in practice is the enforced hybrid_review before submitting "
          "and the prompt habits; the advisor was offered and not used. Whether a different prompt, a higher effort level, or putting the advice into tool results the agent already reads would change that is untested.", "",
          "Limits: ten seeds each, one data version, generated notes, low effort."]
    open(os.path.join(ROOT, "docs", "release4_agent_results.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
