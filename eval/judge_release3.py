"""Judge the release 3 runs with j3.3 (and, beside it, the frozen j3.2) and write docs/judge_release3.md. Free: no model.

Writes experiments/<run>/usefulness_rules_33.jsonl for each of the 30 runs (3 arms x 10 seeds). Usage: python eval/judge_release3.py
"""
import collections
import json
import os
import statistics as st
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import judge_rules_32 as j32  # noqa: E402
import judge_rules_33 as j33  # noqa: E402

SEEDS = [2525, 2626, 2727, 2828, 2929, 3030, 3131, 3232, 3333, 3434]
ARMS = (("r3w2", "workflow v2.2"), ("r3w", "workflow v2.3"), ("r3a", "agent v3.3"))


def main():
    rows = {}
    for pre, _ in ARMS:
        for seed in SEEDS:
            rid, code = f"{pre}_{seed}", f"r3_{seed}"
            args = (os.path.join(ROOT, "data", f"synthetic_v2_{code}", f"view_{rid}"), os.path.join(ROOT, "experiments", code, "flagged.csv"),
                    os.path.join(ROOT, "experiments", rid, "case_summaries_checked.jsonl"))
            run_dir = os.path.join(ROOT, "experiments", rid)
            new = j33.run(*args, os.path.join(run_dir, "usefulness_rules_33.jsonl"), run_dir=run_dir)
            old = j32.run(*args, "/tmp/_j32.jsonl", run_dir=run_dir)
            lean = {x["provider_id"]: x["summary"]["leaning"] for x in map(json.loads, open(args[2]))}
            rows[rid] = [{"lean": lean[a["provider_id"]], "s33": a["score"], "s32": b["score"], "tier33": a["evidence_tier"], "tier32": b["evidence_tier"],
                          "ded33": a["deductions"]} for a, b in zip(new, old)]
    L = ["# Release 3 summaries judged by j3.3 (and j3.2 beside it)", "", "[Back to the README](../README.md)", "",
         "Generated by `python eval/judge_release3.py`. Free, deterministic. Why j3.3 exists: `eval/judge_rules_33.py` (j3.2 deducts 1.5 from every upcoding call that rests on cloned-notes signs "
         "with supportive charts, the case release 3 added). j3.2 is unchanged. The thresholds of the new tier are rules 2.3's own, so it is not independent of the writer.", "",
         "| Arm | Summaries | Mean j3.3 | Mean j3.2 | Upcoding calls | Mean j3.3 on them | Mean j3.2 on them | Upcoding calls on cloning signs |", "|---|---|---|---|---|---|---|---|"]
    for pre, name in ARMS:
        r = [x for rid, l in rows.items() if rid.startswith(pre + "_") for x in l]
        up = [x for x in r if x["lean"] == "pattern_consistent_with_upcoding"]
        cl = [x for x in up if x["tier33"] == "cloning_signs"]
        L.append(f"| {name} | {len(r)} | {st.mean(x['s33'] for x in r):.2f} | {st.mean(x['s32'] for x in r):.2f} | {len(up)} | {st.mean(x['s33'] for x in up):.2f} | "
                 f"{st.mean(x['s32'] for x in up):.2f} | {len(cl)} |")
    allr = [x for l in rows.values() for x in l]
    cl = [x for x in allr if x["lean"] == "pattern_consistent_with_upcoding" and x["tier33"] == "cloning_signs"]
    L += ["", f"On the {len(cl)} upcoding calls that rest on cloning signs, j3.2 gave a mean {st.mean(x['s32'] for x in cl):.2f} and j3.3 {st.mean(x['s33'] for x in cl):.2f}. "
          f"Deductions j3.3 still applies to them: {dict(collections.Counter(k for x in cl for k in x['ded33']))}.",
          "", "Scores agree on every other summary except where the tier changed: "
          f"{sum(x['s32'] != x['s33'] for x in allr)} of {len(allr)} summaries score differently under the two judges.",
          "", "Usefulness is a defect count on the written summary, not whether the finding is right; it is reported beside the upcoders-found result, not instead of it. "
          "Not checked against a person (the human spot check, #93 and #19, is still open)."]
    open(os.path.join(ROOT, "docs", "judge_release3.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
