"""Issue 93 / #19: score the human spot check once docs/human_spot_check.csv is filled in, and write docs/human_spot_check_results.md.

For every row with a score in `your_score_1_to_5`, it recomputes judge j3.2 on that stored summary and reads the stored LLM judge score, then reports
agreement: Spearman correlation, exact and within-one agreement, and per checklist item how often the person and j3.2 say the same (yes/no
columns: y or n). Free; no model is called. Prints a note and writes nothing if no row is scored yet.

Usage:
    python eval/spot_check_93.py
"""
import csv
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import judge_eval_93 as je  # noqa: E402

ITEMS = ("leaning_explained", "observed_vs_expected", "excess_stated", "chart_state", "next_step_fits_leaning")


def main():
    sheet = os.path.join(ROOT, "docs", "human_spot_check.csv")
    rows = [r for r in csv.DictReader(open(sheet)) if r["your_score_1_to_5"].strip()]
    if not rows:
        print("No row of docs/human_spot_check.csv is scored yet; fill in your_score_1_to_5 (and the y/n columns) first.")
        return
    runs = {r["rid"]: r for r in je.runs()}
    people, j32s, llms, item_agree, item_n = [], [], [], {k: 0 for k in ITEMS}, {k: 0 for k in ITEMS}
    for row in rows:
        r = runs[row["run_id"]]
        J = je.Run(r)
        rec = next(x for x in je.jl(os.path.join(r["dir"], "case_summaries_checked.jsonl")) if x["provider_id"] == row["provider_id"])
        s = J.score32(rec)
        llm_path = os.path.join(r["dir"], "usefulness.jsonl")
        llm = {x["provider_id"]: x["score"] for x in je.jl(llm_path)} if os.path.exists(llm_path) else {}
        people.append(int(row["your_score_1_to_5"]))
        j32s.append(s["score"])
        llms.append(llm.get(row["provider_id"]))
        for k in ITEMS:
            v = row[k].strip().lower()[:1]
            if v in ("y", "n"):
                item_n[k] += 1
                item_agree[k] += (v == "y") == bool(s["checklist"][k])
    pairs_llm = [(p, l) for p, l in zip(people, llms) if l is not None]
    n = len(people)
    lines = ["# Human spot check: results (issues 93 and 19)", "", "[Back to the README](../README.md)", "",
             f"Generated by `python eval/spot_check_93.py` from {n} scored rows of `docs/human_spot_check.csv`.", "",
             "| Against the person | Spearman | Exact | Within one |", "|---|---|---|---|",
             f"| j3.2 (rule judge) | {je.spearman(people, j32s):.2f} | {sum(a == b for a, b in zip(people, j32s)) / n:.0%} | {sum(abs(a - b) <= 1 for a, b in zip(people, j32s)) / n:.0%} |"]
    if len(pairs_llm) >= 3:
        a, b = zip(*pairs_llm)
        lines.append(f"| LLM judge (side note) | {je.spearman(list(a), list(b)):.2f} | {sum(x == y for x, y in pairs_llm) / len(pairs_llm):.0%} | "
                     f"{sum(abs(x - y) <= 1 for x, y in pairs_llm) / len(pairs_llm):.0%} |")
    lines += ["", "| Checklist item | Rows answered | Person and j3.2 agree |", "|---|---|---|"]
    for k in ITEMS:
        lines.append(f"| {k.replace('_', ' ')} | {item_n[k]} | " + (f"{item_agree[k] / item_n[k]:.0%}" if item_n[k] else "–") + " |")
    lines += ["", "Adjust j3.2's deductions only on this evidence, and ship any change as a new judge version (j3.2 is never edited after it is used)."]
    out = os.path.join(ROOT, "docs", "human_spot_check_results.md")
    open(out, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
