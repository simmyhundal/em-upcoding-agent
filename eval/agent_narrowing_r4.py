"""Release 4 groundwork: how does agent v3.3 narrow the wide list, and what could the fixed workflow take from it? Free (stored runs and the answer key).

Reads the ten release 3 seeds (2525 to 3434) and the ten release 2 seeds (1515 to 2424). Both sets are development data for release 4 from here on (this
analysis has looked at them). Writes docs/release4_agent_narrowing.md.
"""
import collections
import csv
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
import case_summary as cs  # noqa: E402
import summary_rules as sr  # noqa: E402

R3 = [2525, 2626, 2727, 2828, 2929, 3030, 3131, 3232, 3333, 3434]
R2 = [1515, 1616, 1717, 1818, 1919, 2020, 2121, 2222, 2323, 2424]


def listed(code, seeds):
    out = []
    for s in seeds:
        key = json.load(open(os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_{code}_{s}.json")))["providers"]
        for r in csv.DictReader(open(os.path.join(ROOT, "experiments", f"{code}_{s}", "flagged_eb_ratio_t_10.csv"))):
            if r["flagged"] == "True":
                exp = float(r["expected_share"])
                out.append({"seed": s, "pid": r["provider_id"], "rank": int(r["rank"]), "ratio": float(r["share_99215"]) / exp if exp else 0.0,
                            "up": key[r["provider_id"]]["role"] == "upcoder"})
    return out


def agent_requests(seed):
    req = set()
    for line in open(os.path.join(ROOT, "experiments", f"r3a_{seed}", "audit.jsonl")):
        e = json.loads(line)
        if e["tool"] == "request_records":
            req.add(e["args"].get("provider_id") or e["args"].get("provider"))
    return req


def rounds(rid, key):
    n, asked = 0, set()
    for line in open(os.path.join(ROOT, "experiments", rid, "office_transcript.jsonl")):
        e = json.loads(line)
        if e.get("action") in ("send_request", "follow_up") and "error" not in e and key[e["provider_id"]]["role"] != "upcoder":
            n += 1
            asked.add(e["provider_id"])
    return len(asked), n


def main():
    L = ["# Release 4 groundwork: how agent v3.3 narrows the wide list", "", "[Back to the README](../README.md)", "",
         "Generated by `python eval/agent_narrowing_r4.py`. Free: stored runs and the answer key. The ten release 2 seeds and the ten release 3 seeds are development data for release 4 "
         "from here on, because this analysis has looked at them; release 4 needs fresh seeds.", ""]
    test, dev = listed("r3", R3), listed("r2", R2)
    L += ["## 1. What the agent asked for (release 3 seeds)", ""]
    asked = {(s, p) for s in R3 for p in agent_requests(s)}
    in_list = {(r["seed"], r["pid"]): r for r in test}
    a_rows = [in_list[k] for k in asked if k in in_list]
    not_asked = [r for k, r in in_list.items() if k not in asked]
    L += [f"- The agent requested records for {len(asked)} providers; {len(a_rows)} were on the top-10% list it started from (no provider outside it).",
          f"- Ratio of billed 99215 share to expected share: {sum(r['ratio'] >= 3 for r in a_rows) / len(a_rows):.0%} of the providers it asked had a ratio of 3 or more (the lowest was {min(r['ratio'] for r in a_rows):.2f}); "
          f"of the {len(not_asked)} list members it did not ask, {sum(r['ratio'] >= 3 for r in not_asked)} had a ratio of 3 or more. In effect it asks where the screen table's ratio is at least 3. "
          "Part of this is the v3.1 rule that every screened provider at 3 or more times expected needs a finding or a reason it was set aside; its set-aside reasons read \"2.9x expected, below 3x\".",
          f"- Upcoders on the list it did not ask: {sum(r['up'] for r in not_asked)} of {sum(r['up'] for r in test)} on the list.", ""]
    L += ["## 2. What the same gate would do to the fixed workflow's list", "",
          "| Ratio to expected at least | Release 3 seeds: providers asked | of them honest | upcoders kept of " + str(sum(r["up"] for r in test)) + " | Release 2 seeds: asked | honest | upcoders kept of " + str(sum(r["up"] for r in dev)) + " |",
          "|---|---|---|---|---|---|---|"]
    for t in (0, 2.5, 3, 3.5, 4):
        a, b = [r for r in test if r["ratio"] >= t], [r for r in dev if r["ratio"] >= t]
        L.append(f"| {t:g} | {len(a)} | {sum(not r['up'] for r in a)} | {sum(r['up'] for r in a)} | {len(b)} | {sum(not r['up'] for r in b)} | {sum(r['up'] for r in b)} |")
    L += ["", "(Whole list = ratio 0. Workflow v2.3 asked every one of the list's providers: 150 honest practices on the release 3 seeds.)", ""]
    L += ["## 3. Follow-up rounds on honest practices", "", "| Arm | Honest practices asked | Rounds on them | Rounds per practice |", "|---|---|---|---|"]
    for pre, name in (("r3w2", "workflow v2.2"), ("r3w", "workflow v2.3"), ("r3a", "agent v3.3")):
        a = r = 0
        for s in R3:
            key = json.load(open(os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_r3_{s}.json")))["providers"]
            x, y = rounds(f"{pre}_{s}", key)
            a, r = a + x, r + y
        L.append(f"| {name} | {a} | {r} | {r / a:.1f} |")
    L += ["", "## 4. When the agent has charts, does it read them like rules 2.3?", ""]
    tot = collections.Counter()
    for s in R3:
        key = json.load(open(os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_r3_{s}.json")))["providers"]
        out = cs.run(os.path.join(ROOT, "data", f"synthetic_v2_r3_{s}", f"view_r3a_{s}"), os.path.join(ROOT, "experiments", f"r3_{s}", "flagged_eb_ratio_t_10.csv"),
                     f"/tmp/ag{s}.jsonl", dry_run=True, rules="2.3")
        agent = {x["provider_id"]: x["summary"]["leaning"] for x in map(json.loads, open(os.path.join(ROOT, "experiments", f"r3a_{s}", "case_summaries_checked.jsonl")))}
        for o in out:
            pid = o["provider_id"]
            if key[pid]["role"] != "upcoder":
                continue
            rule_up = sr.rule_leaning_23(o["packet"])[0] == sr.UPCODING
            tot[("rules 2.3 on the agent's records say upcoding" if rule_up else "rules 2.3 on the agent's records do not", agent.get(pid) == sr.UPCODING, pid in agent)] += 1
    for (rule, ag, has), v in sorted(tot.items(), key=lambda kv: (kv[0][0], not kv[0][1])):
        L.append(f"- Upcoders where {rule}; agent {'called upcoding' if ag else ('wrote another leaning' if has else 'wrote no finding')}: {v}")
    L += ["", "So the agent's reading of charts matches the rules; what separates the arms is evidence gathering (which providers, how many charts, how many follow-ups).", "",
          "## What this suggests for release 4 (hypotheses, not results)", "",
          "- Gate the workflow's light tier on the ratio to expected (3 or more), as the agent does, and cap follow-up rounds there; measure honest practices asked per upcoder found "
          "(W2.2 64/24, W2.3 150/37, A3.3 79/34 on the release 3 seeds).",
          "- Give the agent the deterministic parts the workflow gets for free: run `hybrid_review` on every provider whose records arrived, and stop spending rounds on practices whose first sample is clean.",
          "- Re-test the gate on fresh seeds; it costs reach (at ratio 3, about a quarter of the listed upcoders sit below it)."]
    open(os.path.join(ROOT, "docs", "release4_agent_narrowing.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
