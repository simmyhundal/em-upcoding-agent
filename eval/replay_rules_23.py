"""Issue 99: free replay of rules 2.3 on the stored release 2 workflow runs (r2w_<seed>, data 2.2, 10 seeds). No model calls, no new data.

Rebuilds each run's case packets from its stored records (case_summary.run dry run), checks that rules 2.2 reproduce the stored leanings exactly (the
replay is faithful), then applies rules 2.3 (summary_rules.rule_leaning_23) and scores both against the answer key: upcoders called, honest doctors
called, and what changed. IN-SAMPLE: these seeds suggested the rule (they are development data for release 3), so the result shows what the rule can
do on data it was read from, not how it generalises; a fresh batch is the test. Only the leaning is replayed (the text, the follow-up requests and the
audit-trail request are not).

Usage: python eval/replay_rules_23.py   (writes docs/replay_rules_23.md)
"""
import json
import os
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
import case_summary as cs  # noqa: E402
import summary_rules as sr  # noqa: E402

SEEDS = [1515, 1616, 1717, 1818, 1919, 2020, 2121, 2222, 2323, 2424]
UP = sr.UPCODING


def replay():
    rows = []
    for seed in SEEDS:
        key = json.load(open(os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_r2_{seed}.json")))["providers"]
        out = cs.run(os.path.join(ROOT, "data", f"synthetic_v2_r2_{seed}", f"view_r2w_{seed}"),
                     os.path.join(ROOT, "experiments", f"r2w_{seed}", "flagged_eb_ratio_top5pct.csv"), os.path.join("/tmp", f"replay23_{seed}.jsonl"),
                     dry_run=True, rules="2.2")
        stored = {x["provider_id"]: x for x in map(json.loads, open(os.path.join(ROOT, "experiments", f"r2w_{seed}", "case_summaries_checked.jsonl")))}
        for o in out:
            pk, pid = o["packet"], o["provider_id"]
            l22, _ = sr.rule_leaning_22(pk)
            l23, why = sr.rule_leaning_23(pk)
            st = stored[pid]["summary"]["leaning"]
            v = key[pid]
            rows.append({"seed": seed, "pid": pid, "role": v["role"], "clones": bool(v.get("clones_notes")), "stored": st, "l22": l22, "l23": l23,
                         "faithful": (l22 == st) or (l22 is None and st == "inconclusive"), "why": why})
    return rows


def kind(r):
    return "honest doctor" if r["role"] != "upcoder" else ("upcoder, cloned notes" if r["clones"] else "upcoder, honest notes")


def main():
    rows = replay()
    n = len(rows)
    faithful = sum(r["faithful"] for r in rows)
    L = ["# Replay of rules 2.3 on the release 2 workflow runs (issue 99)", "", "[Back to the README](../README.md)", "",
         "Generated by `python eval/replay_rules_23.py`. Free: stored records only, no model calls. **In sample**: the rule was suggested by reading these ten seeds "
         "(1515 to 2424, now development data for release 3), so this shows what it can do on data it came from, not how it generalises. A fresh 10-seed batch is the test "
         "(posted in advance). Data stays 2.2 for release 3.", "",
         "Rule 2.3 (`summary_rules.rule_leaning_23`): where rules 2.2 would say inconclusive or still ask the model, lean upcoding when at least 8 notes came back, 12% or more were signed late "
         "(the existing `INFLATED_LATE`), and the 99215 share is more than 3 times the expected share (the existing `MAX_EXCESS_FOR_ACUITY`). A chart-based upcoding call (rules 2.2) must also beat the real, uncapped peer unsupported rate at one-sided exact binomial 0.05; the 15% cap alone let honest doctors through once the list was widened (`dev_release3.md`). No new cutoff was fitted.", "",
         f"**Faithful replay:** rules 2.2 reproduce the stored leaning on {faithful} of {n} providers.", ""]
    L += ["| Seed | Workflow 2.2 called (right / wrong) | Rules 2.3 called (right / wrong) |", "|---|---|---|"]
    tot = Counter()
    for s in SEEDS:
        x = [r for r in rows if r["seed"] == s]
        a = (sum(r["l22"] == UP and r["role"] == "upcoder" for r in x), sum(r["l22"] == UP and r["role"] != "upcoder" for r in x))
        b = (sum(r["l23"] == UP and r["role"] == "upcoder" for r in x), sum(r["l23"] == UP and r["role"] != "upcoder" for r in x))
        tot.update({"a_right": a[0], "a_wrong": a[1], "b_right": b[0], "b_wrong": b[1]})
        L.append(f"| {s} | {a[0]} / {a[1]} | {b[0]} / {b[1]} |")
    L.append(f"| **Total** | **{tot['a_right']} / {tot['a_wrong']}** | **{tot['b_right']} / {tot['b_wrong']}** |")
    n_up = 78
    pa = tot["a_right"] / (tot["a_right"] + tot["a_wrong"])
    pb = tot["b_right"] / (tot["b_right"] + tot["b_wrong"])
    L += ["", f"Recall of the workflow's leanings: {tot['a_right']} of {n_up} ({tot['a_right'] / n_up:.0%}) with rules 2.2, {tot['b_right']} of {n_up} ({tot['b_right'] / n_up:.0%}) with rules 2.3. "
          f"Precision of the calls: {pa:.0%} against {pb:.0%}.", "",
          "| Kind of provider | Called by rules 2.2 | Called by rules 2.3 | Newly called |", "|---|---|---|---|"]
    for k in ("upcoder, cloned notes", "upcoder, honest notes", "honest doctor"):
        g = [r for r in rows if kind(r) == k]
        L.append(f"| {k} | {sum(r['l22'] == UP for r in g)} | {sum(r['l23'] == UP for r in g)} | {sum(r['l23'] == UP and r['l22'] != UP for r in g)} |")
    new_wrong = [r for r in rows if r["l23"] == UP and r["l22"] != UP and r["role"] != "upcoder"]
    L += ["", "Newly called honest doctors: " + (", ".join(f"{r['pid']} (seed {r['seed']}, {r['role']})" for r in new_wrong) or "none") + ".", "",
          "## What this does not show", "",
          "- It is a leaning replay. Providers called upcoding would get the existing next steps, which is a records follow-up and review by a person, not an accusation.",
          "- It cannot show the audit-trail request (the office decides whether to answer it) or any agent change.",
          "- The late-signature signal is planted by the generator (`clone_signal_strength` in `src/notes_v21.py`), so real notes will be harder.",
          "- Only the providers the screen listed (top 5%) are covered; 34 of 78 upcoders were never listed (`release2_misses.md`)."]
    open(os.path.join(ROOT, "docs", "replay_rules_23.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
