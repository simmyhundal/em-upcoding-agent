"""Threshold sweep: what each suspicion cutoff would flag, and how many of them are real upcoders.

Uses the risk-adjusted score (`z_adj`) already saved in each run's flagged file, so no data folder is needed. Needs the answer
key (eval only). Datasets come from experiments/runs.json.

Usage:
    python eval/threshold_sweep.py                      # prints markdown for every dataset
    python eval/threshold_sweep.py --write docs/threshold_sweep.md
"""
import argparse
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THRESHOLDS = (2, 3, 4, 5, 6, 8, 10, 12, 15)


def sweep(rows, truth, thresholds=THRESHOLDS):
    roles = {p: v["role"] for p, v in truth["providers"].items()}
    out = []
    for t in thresholds:
        sel = [r for r in rows if float(r["z_adj"]) >= t]
        c = {k: sum(1 for r in sel if roles[r["provider_id"]] == k) for k in ("upcoder", "hard_negative", "normal")}
        out.append({"threshold": t, "flagged": len(sel), **c,
                    "precision": (c["upcoder"] / len(sel)) if sel else None})
    return out


def markdown(label, res, total_upcoders):
    lines = [f"### {label}", "",
             f"| Suspicion at or above | Flagged | Upcoders caught (of {total_upcoders}) | Honest, sicker-panel | Honest, ordinary | Precision |",
             "|---|---|---|---|---|---|"]
    for r in res:
        p = "–" if r["precision"] is None else f"{r['precision']:.0%}"
        lines.append(f"| {r['threshold']} | {r['flagged']} | {r['upcoder']} | {r['hard_negative']} | {r['normal']} | {p} |")
    return "\n".join(lines)


def build(registry_path=None):
    reg = json.load(open(registry_path or os.path.join(ROOT, "experiments", "runs.json")))
    parts = ["# Suspicion threshold sweep", "",
             "How many providers each cutoff on the risk-adjusted score flags, and how many of them are real upcoders. "
             "Compare with the top-25 list, which flags 25 providers at about 32% precision on both datasets. "
             "Generated by `python eval/threshold_sweep.py --write docs/threshold_sweep.md` (needs the gitignored answer keys).", ""]
    for d in reg["datasets"].values():
        truth = json.load(open(os.path.join(ROOT, d["truth"])))
        rows = list(csv.DictReader(open(os.path.join(ROOT, d["flagged"]))))
        n_up = sum(1 for v in truth["providers"].values() if v["role"] == "upcoder")
        parts += [markdown(d["label"], sweep(rows, truth), n_up), ""]
    parts += ["A cutoff of 5 catches every upcoder on both datasets with 11 and 9 providers flagged (precision 73% and 89%). "
              "It was chosen after looking at seed 42 and then checked on seed 101, which had already been looked at, so treat it as "
              "a reasonable starting point, not a tuned or validated setting. Lower cutoffs buy nothing here: recall is already 100% at 5."]
    return "\n".join(parts) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--write")
    a = ap.parse_args()
    md = build()
    if a.write:
        open(os.path.join(ROOT, a.write), "w").write(md)
    print(md)
