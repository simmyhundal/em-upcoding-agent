"""Apply the release 2 screen rule (fixed on issue 90 before any result was seen) to the first-batch datasets. Free: claims only, answer key for scoring.

Rule: score zscore, riskadj, priority and eb_ratio on the 8 first-batch datasets (seeds 1515 to 2222, 216 doctors, data 2.2). The screen for both live
arms is whichever of eb_ratio and priority has more upcoders in the top 5% (11 providers) summed over the seeds; ties go to the higher mean AUPRC.
riskadj and zscore are reported but cannot be chosen.

Usage:
    python eval/release2_screen_choice.py [--write]      # --write writes docs/release2_screen_choice.md
"""
import json
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import screen_methods_eval as se  # noqa: E402

SEEDS = [1515, 1616, 1717, 1818, 1919, 2020, 2121, 2222]
METHODS = ["zscore", "riskadj", "priority", "eb_ratio"]
CANDIDATES = ["eb_ratio", "priority"]


def run():
    out = []
    for s in SEEDS:
        view = os.path.join(ROOT, "data", f"synthetic_v2_r2_{s}", "view")
        truth = json.load(open(os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_r2_{s}.json")))
        out.append(se.evaluate_dataset(view, truth, f"seed {s}"))
        print("scored", s, file=sys.stderr)
    return out


def summary(res, pct=5):
    n_up = sum(r["upcoders"] for r in res)
    rows = {}
    for m in METHODS:
        k_found = k_flagged = top25 = 0
        auprc = 0.0
        for r in res:
            k = max(1, math.ceil(r["providers"] * pct / 100))
            ranks = r["methods"][m]["ranks"].values()
            k_found += sum(1 for rk in ranks if rk <= k)
            k_flagged += k
            top25 += r["methods"][m]["found"]
            auprc += r["methods"][m]["auprc"]
        rows[m] = {"found": k_found, "flagged": k_flagged, "top25": top25, "auprc": auprc / len(res)}
    return n_up, rows


def choose(rows):
    return max(CANDIDATES, key=lambda m: (rows[m]["found"], rows[m]["auprc"]))


def report(res):
    n_up, rows = summary(res)
    ch = choose(rows)
    lines = ["| Screen | Upcoders in the top 5% (11 per dataset) | Honest doctors flagged | Upcoders in the top 25 (reference) | Mean AUPRC |", "|---|---|---|---|---|"]
    for m in METHODS:
        r = rows[m]
        mark = " (cannot be chosen)" if m not in CANDIDATES else ""
        lines.append(f"| `{m}`{mark} | {r['found']} of {n_up} | {r['flagged'] - r['found']} | {r['top25']} of {n_up} | {r['auprc']:.3f} |")
    per = ["| Seed | Upcoders | " + " | ".join(f"`{m}` top 5%" for m in METHODS) + " |", "|---|---|" + "---|" * len(METHODS)]
    for r in res:
        k = math.ceil(r["providers"] * 5 / 100)
        per.append(f"| {r['label']} | {r['upcoders']} | " + " | ".join(str(sum(1 for rk in r["methods"][m]["ranks"].values() if rk <= k)) for m in METHODS) + " |")
    return ("# Release 2 screen choice (rule fixed on issue 90 before any result)\n\n[Back to the README](../README.md)\n\n"
            "Generated by `python eval/release2_screen_choice.py --write`. Free: claims only; the answer key only scores. The first batch of the release 2 evaluation "
            "([#90](https://github.com/simmyhundal/em-upcoding-agent/issues/90)): seeds 1515, 1616, 1717, 1818, 1919, 2020, 2121, 2222, each 216 doctors, 8 planted upcoders, 8 high-acuity "
            "doctors, half the upcoders cloning notes, data 2.2 defaults, payer-based upcoder definition.\n\n"
            "**Rule (written on #90 before any result was seen):** the screen for both live arms is whichever of `eb_ratio` and `priority` has more upcoders in the top 5% summed over the "
            "8 seeds; ties go to the higher mean AUPRC. `riskadj` and `zscore` are reported but cannot be chosen.\n\n"
            f"## Result: **`{ch}`**\n\n" + "\n".join(lines) + "\n\n## Per seed\n\n" + "\n".join(per) + "\n\n"
            "Notes. The upcoder count is 62 of 64 planted because two planted upcoders sit on panels with so many 99215-level visits that their true overbilling rate is under the "
            "line ([data_v2_2.md](data_v2_2.md)). The definition was changed from realised to true rates after the data was generated and before any screen result was computed (the "
            "realised version labeled 11 honest doctors upcoders). 8 datasets, one draw each: a difference of a few upcoders is within noise, so this only picks the screen for a "
            "$10 comparison of workflow against agent; it does not confirm the screen. Confirmation needs the second-batch seeds, and the older 14 datasets are development data.\n")


if __name__ == "__main__":
    res = run()
    t = report(res)
    print(t)
    if "--write" in sys.argv:
        open(os.path.join(ROOT, "docs", "release2_screen_choice.md"), "w").write(t)
