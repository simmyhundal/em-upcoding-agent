"""S4.1 first step (issue 146): the copy fee set to $0 (commercial profile) against score 4.0's $90, on the stored runs. Free: re-scores stored run folders with score 4.0's functions under each profile
(no model calls). Writes docs/score_41.md. Usage: python eval/score_41_sensitivity.py"""
import os
import statistics as st
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import dev_pool_v4 as pool  # noqa: E402
import recovery_41 as r41  # noqa: E402
import score_40 as s4  # noqa: E402

FRESH = [5555 + 101 * i for i in range(10)]
ARMS_FRESH = [("Workflow v2.5 (frozen)", "fr25"), ("Workflow v4.0", "fr40"), ("Agent v5.0", "fra50")]
DEV = [s for b in pool.BATCHES for s in b]


def total(pre, code_fmt, seeds, profile):
    p = r41.params41(profile)
    rows = [s4.from_run(f"{pre}_{s}", code_fmt.format(s), p=p) for s in seeds]
    return {k: sum(r[k] for r in rows) for k in ("score", "recovered", "staff_cost", "abrasion", "found", "demands", "rounds")}, rows


def main():
    L = ["# Score 4.1 (S4.1), step one: the records copy fee (issue 146)", "", "[Back to the README](../README.md) · [score 4.0 (S4.0)](score_40.md) · [commercial recovery profiles, issue 146](https://github.com/simmyhundal/em-upcoding-agent/issues/146)", "",
         "Generated by `python eval/score_41_sensitivity.py`. **Free:** stored runs re-scored, no model calls. Abbreviations: S4.0 and S4.1 are score versions, D4.0 is data 4.0, W4.0 and A5.0 are workflow v4.0 and agent v5.0.", "",
         "## What changed", "",
         "S4.0 charges **$90 per request round** for copying records (CMS Transmittal 786: what a Medicare contractor pays a provider). S4.1 adds plan-type profiles in `src/recovery_41.py`. The default, `commercial_no_copy`, sets the copy fee to **$0**, on the "
         "**assumption** that many commercial provider contracts require records for audits at no charge. That assumption has not been checked against contracts or state rules; it is part of the commercial-profile work in issue 146. "
         "S4.0 is unchanged, so S4.0 numbers stay comparable. Nothing else differs in this step (staff-hours, abrasion and recovery rules are S4.0's).", "",
         "## Ten fresh D4.0 seeds (5555 to 6464), totals over ten seeds", "", "| Arm | S4.0 (copy $90) | S4.1 (copy $0) | Rounds | Copy fees removed | Found of 80 |", "|---|---|---|---|---|---|"]
    for label, pre in ARMS_FRESH:
        a, _ = total(pre, "f4_{}", FRESH, "medicare_like")
        b, _ = total(pre, "f4_{}", FRESH, "commercial_no_copy")
        L.append(f"| {label} | {a['score']:,.0f} | {b['score']:,.0f} | {a['rounds']:.0f} | {a['score'] and (b['score'] - a['score']):,.0f} | {a['found']:.0f} |")
    L += ["", "## 100 D4.0 development seeds, workflow v4.0 and the frozen v2.5, per seed", "", "| Arm | S4.0 per seed | S4.1 per seed |", "|---|---|---|"]
    for label, pre in (("Frozen workflow v2.5 (R0)", "wlr0"), ("Workflow v4.0 (H8)", "wlh8")):
        a, ra = total(pre, "d4_{}", DEV, "medicare_like")
        b, rb = total(pre, "d4_{}", DEV, "commercial_no_copy")
        L.append(f"| {label} | {a['score'] / len(DEV):,.0f} | {b['score'] / len(DEV):,.0f} |")
    L += ["", "## Reading", "",
          "- The copy fee is a third of workflow v4.0's staff cost on the fresh seeds. Removing it moves every arm up by the same amount per round, so the order of the arms does not change; the cheaper-asking arms gain least.",
          "- **No arm is above zero on the fresh seeds under S4.1 either**: the gap is mostly chart review, request administration and demand work against recoveries of a few hundred dollars per seed.",
          "- The ask model of W4.0 was fitted under S4.0's prices. Cheaper asking would change whom it asks; refitting it under S4.1 is a separate step (a new hypothesis, not done here).",
          "- Still S4.0 in this step: the Medicare-style recovery rules (90% lower bound, 15% error gate, netting), the staff-minute assumptions, abrasion, and Medicare-sized dollars per provider (issue 145). Look-back, appeals, collection rate and contract extrapolation rights are the next S4.1 steps."]
    open(os.path.join(ROOT, "docs", "score_41.md"), "w").write("\n".join(L) + "\n")
    print("wrote docs/score_41.md")


if __name__ == "__main__":
    main()
