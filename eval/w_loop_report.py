"""Batch-by-batch scores of the workflow versions in the RL loop (issue 131), from experiments/w_loop/*.json. Free. Writes docs/w_loop_v4.md. Usage: python eval/w_loop_report.py"""
import json
import os
import statistics as st
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import dev_pool_v4 as pool  # noqa: E402
import w_loop as wl  # noqa: E402

SHOW = [("R0", "R0: frozen workflow v2.5"), ("R0u", "R0u: v2.5 with the eb_upper_t list"), ("H1", "H1: + rules 4.0"), ("H4", "H4: H1 without escalation"), ("H6", "H6: H4 + demand floor"),
        ("H8", "**H8: H6 + ask-or-skip refitted on score 4.0 = workflow v4.0**")]
REJECTED = [("H2", "H1 + first sample within the 99214 and 99215 claims"), ("H3", "H2 without escalation"), ("H5", "H1 asking every listed provider"), ("H7", "H6 + rules 4.1 (time padding, risk inflation)"),
            ("H9", "H8 + demand floor at twice the demand cost"), ("H10", "H8 + first sample of 20 charts"), ("H11", "H8 + first sample of 45 charts"), ("H12", "H8 + ask model refitted on batches 1 to 6")]


def main():
    data = {n: json.load(open(os.path.join(wl.CACHE_DIR, f"{n}.json"))) for n, _ in SHOW + REJECTED if os.path.exists(os.path.join(wl.CACHE_DIR, f"{n}.json"))}
    L = ["# The workflow's RL loop on data 4.0 and score 4.0: batch by batch (issue 131)", "", "[Back to the README](../README.md) · [v4/v5 plan](v4_v5_plan.md) · [score 4.0](score_40.md) · [data 4.0](data_v4_0.md)", "",
         "Generated by `python eval/w_loop_report.py`. **Free** (API-free workflow versions). 100 data 4.0 development seeds in ten batches of ten (`eval/dev_pool_v4.py`); score 4.0 per seed (`eval/score_40.py`); versions in `eval/w_loop.py`. "
         "Fresh seeds (5555 and above) were never run here. The model of H8 was fitted on batches 1 to 4, so **batches 5 to 10 are out of sample for it**; H6 and earlier have no fitted part beyond the frozen v2.5 policy.", "",
         "## Score 4.0 per seed, by batch", "", "| Version | " + " | ".join(f"B{b}" for b in range(1, 11)) + " | All 100 | Batches 5 to 10 |", "|---|" + "---|" * 12]
    for n, label in SHOW:
        if n not in data:
            continue
        d = data[n]
        cells = []
        for b in range(1, 11):
            seeds = [str(s) for s in pool.BATCHES[b - 1]]
            cells.append(f"{st.mean(d[s]['score'] for s in seeds):,.0f}" if all(s in d for s in seeds) else "-")
        allm = st.mean(v["score"] for v in d.values()) if len(d) == 100 else None
        oos = [str(s) for b in range(5, 11) for s in pool.BATCHES[b - 1]]
        L.append(f"| {label} | " + " | ".join(cells) + f" | {allm:,.0f} |" if allm is not None else f"| {label} | " + " | ".join(cells) + " | - |")
        L[-1] += f" {st.mean(d[s]['score'] for s in oos):,.0f} |" if all(s in d for s in oos) else " - |"
    L += ["", "## Upcoders found, honest providers called and rounds (all 100 seeds, 800 planted upcoders)", "", "| Version | Score 4.0 per seed | Found | Honest called | Rounds | Recovered per seed | Staff-hours cost per seed |", "|---|---|---|---|---|---|---|"]
    for n, label in SHOW:
        d = data.get(n)
        if d and len(d) == 100:
            L.append(f"| {label} | {st.mean(v['score'] for v in d.values()):,.0f} | {sum(v['found'] for v in d.values())} | {sum(v['honest_called'] for v in d.values())} | {sum(v['rounds'] for v in d.values())} | "
                     f"{st.mean(v['recovered'] for v in d.values()):,.0f} | {st.mean(v['staff_cost'] for v in d.values()):,.0f} |")
    c = {}
    for ref, name in (("R0", "H8"), ("H6", "H8")):
        seeds = [s for b in range(5, 11) for s in pool.BATCHES[b - 1]] if ref == "H6" else sum(pool.BATCHES, [])
        c[(name, ref)] = wl.compare(name, ref, seeds)
    L += ["", "## The result", "", "- " + wl.line(c[("H8", "R0")], "H8 (workflow v4.0)", "R0 (frozen v2.5)") + ".", "- " + wl.line(c[("H8", "H6")], "H8", "H6") + " (batches 5 to 10, out of sample for H8's model).", "",
          "## Hypotheses tried (twelve, so Bonferroni alpha 0.0042)", "", "| Version | Change | Outcome |", "|---|---|---|", "| R0u | frozen v2.5 with the eb_upper_t list | confirmed: +\\$8.9k per seed over R0, 20 of 20 seeds |",
          "| H1 | R0u + rules 4.0 | more found (66 vs 35 over 40 seeds), score gain not confirmed on unseen batches (p = 0.125 and 0.047) |", "| H4 | H1 without escalation | confirmed on the unseen batch 3 (+\\$1.0k, 10 of 10) |",
          "| H6 | H4 + demand floor | confirmed on the unseen batch 4 (+\\$263, 8 of 10, p = 0.0039) |", "| **H8** | H6 + ask-or-skip refitted on score 4.0 | **confirmed on the unseen batches 5 and 6 (+\\$679, 16 of 20, p = 0.0006)** |"]
    for n, label in REJECTED:
        L.append(f"| {n} | {label} | rejected |")
    L += ["", "Rejected means no improvement over the version it was tested against (details and numbers in the issue's comments). Per-version options: `eval/w_loop.py`; the frozen workflow v4.0 is `workflow_policy_40.FROZEN_V40`."]
    fr = os.path.join(ROOT, "experiments", "v4_fresh_results.json")
    if os.path.exists(fr):
        res = json.load(open(fr))
        L += ["", "## Fresh seeds (5555 to 6464, never tuned on; eval/run_v4_fresh.py)", "", "| Arm | Score 4.0 per seed | Found of 80 | Honest called | Recovered | Staff-hours cost | Rounds |", "|---|---|---|---|---|---|---|"]
        for label, d in res.items():
            L.append(f"| {label} | {st.mean(v['score'] for v in d.values()):,.0f} | {sum(v['found'] for v in d.values())} | {sum(v['honest_called'] for v in d.values())} | "
                     f"{st.mean(v['recovered'] for v in d.values()):,.0f} | {st.mean(v['staff_cost'] for v in d.values()):,.0f} | {sum(v['rounds'] for v in d.values())} |")
        if "W4.0" in res and "W2.5 (frozen)" in res:
            seeds = sorted(res["W4.0"], key=int)
            diffs = [res["W4.0"][x]["score"] - res["W2.5 (frozen)"][x]["score"] for x in seeds]
            L += ["", f"Workflow v4.0 beats the frozen v2.5 by ${st.mean(diffs):,.0f} per seed on {sum(d > 0 for d in diffs)} of {len(diffs)} fresh seeds (exact one-sided p = {wl.perm_p(diffs):.3f}). "
                  "**It did not stay above zero** as it did on the development pool (+$549 per seed): about 10 upcoders were expected from the out-of-sample batches and 3 were found; ten seeds cannot separate noise from a generalization gap of a model fitted on 40 seeds (issue 132)."]
    open(os.path.join(ROOT, "docs", "w_loop_v4.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
