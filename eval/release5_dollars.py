"""Release 5 baseline: every arm in dollars, the primary score of release 5 (issue 109). Free. See eval/dollar_reward.py for the reward (value = the 90% LOWER BOUND of the extrapolated
overpayment, minus sourced costs) and eval/dev_arm_dollars.py for how the workflow arms are re-run on the development seeds (L and GL cross-validated there).

Sets: release 2 seeds (1515 to 2424) and release 3 seeds (2525 to 3434), re-run or stored as in dev_arm_dollars.py; the release 4 fresh seeds (3535 to 4444), from the stored release 4 runs
(L and GL there use the policy fitted on the 20 earlier seeds, so out of sample); and the release 1 seeds for history. Points are NOT the development direction in release 5; they can be
back-scored later from `eval/dev_arm_scores.py`.

Usage: python eval/release5_dollars.py     (writes docs/release5_dollar_baseline.md and experiments/release5_dollar_results.json)
"""
import json
import multiprocessing as mp
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import dev_arm_dollars as dd  # noqa: E402
import dev_release4 as dev4  # noqa: E402
import dollar_reward as dr  # noqa: E402

OUT = os.path.join(ROOT, "experiments", "release5_dollar_results.json")
FRESH = [3535, 3636, 3737, 3838, 3939, 4040, 4141, 4242, 4343, 4444]
TITLES = {"r2": "Release 2 seeds (1515 to 2424)", "r3": "Release 3 seeds (2525 to 3434)", "r4": "Release 4 fresh seeds (3535 to 4444)",
          "r1": "Release 1 seeds (404 to 1313, data 2.0 and 2.1; history only, not comparable with the other tables)"}


def collect():
    fold_of, pols = dd.fold_policies()
    jobs = [(pre, s, c, pols[fold_of[s]] if c in ("L", "GL") else None) for pre, s in dev4.SEEDS for c in dd.CONFIGS]
    with mp.Pool(4) as pool:
        res = pool.map(dd.run_config, jobs)
    for pre, s in dev4.SEEDS:
        res.append({"set": pre, "seed": s, "arm": "A3.2" if pre == "r2" else "A3.3", **dr.from_run(f"{'r2a' if pre == 'r2' else 'r3a'}_{s}", f"{pre}_{s}")})
    for s in FRESH:
        for arm, pre in (("W2.3", "r4w23"), ("G", "r4g"), ("L", "r4l"), ("GL", "r4gl"), ("A3.4", "r4a")):
            res.append({"set": "r4", "seed": s, "arm": arm, **dr.from_run(f"{pre}_{s}", f"r4_{s}")})
    import analyze_eval61 as a61
    r61 = a61.load()
    for arm in a61.ARMS:
        for k in sorted({k for k, _ in r61 if "_r" not in k}, key=lambda k: int(k[1:])):
            r = r61[(k, arm)]
            res.append({"set": "r1", "seed": k, "arm": arm, **dr.from_run(r["run"], r["code"])})
    return res


def main():
    res = json.load(open(OUT)) if os.path.exists(OUT) and "--rerun" not in sys.argv else collect()
    json.dump(res, open(OUT, "w"), indent=1)
    L = ["# Release 5 baseline: every arm in dollars (the primary score), issue 109", "", "[Back to the README](../README.md)", "",
         "Generated by `python eval/release5_dollars.py`. Free. **Net dollars = the 90% lower bound of the overpayment each arm could extrapolate from its own random charts on the upcoders it calls, minus "
         f"its costs** (${dr.C_COPY:.0f} per round for copied records, ${dr.C_BURDEN:.2f} per round to an honest practice, ${dr.C_REVIEW:.0f} per practice reviewed, ${dr.C_FALSE:,.0f} per honest doctor called: "
         "sources and caveats in `eval/dollar_reward.py`; the last is an assumption). Release 5 develops on this score; the release 4 points score is not the development direction and can be back-scored later. "
         "**Caveats:** the dollars are a ranking at the simulated scale (providers have about 240 claims a year); cloned-notes upcoders are worth about nothing here until the recovery model of issue 109 exists; "
         "L and GL are cross-validated on the release 2 and 3 seeds and out of sample on the release 4 seeds.", ""]
    for st in ("r2", "r3", "r4", "r1"):
        arms = list(dict.fromkeys(r["arm"] for r in res if r["set"] == st))
        L += [f"## {TITLES[st]}", "", "| Arm | Upcoders found | Recall | Honest doctors called | Value (lower bound) | Costs | Net $ per seed | Net, honest-call charge $0 | Net, charge $10,000 | Break-even scale |", "|---|---|---|---|---|---|---|---|---|---|"]
        nets = {}
        for a in arms:
            xs = [r for r in res if r["set"] == st and r["arm"] == a]
            c = dr.add(xs)
            n = len(xs)
            cost = dr.C_COPY * c["all_rounds"] + dr.C_BURDEN * c["honest_rounds"] + dr.C_REVIEW * c["reviewed"] + dr.C_FALSE * c["honest_called"]
            nets[a] = dr.net(c) / n
            be = f"{cost / c['value']:.1f}x" if c["value"] else "none"
            L.append(f"| {a} | {c['found']} of {c['upcoders']} | {c['found'] / c['upcoders']:.0%} | {c['honest_called']} | ${c['value']:,.0f} | ${cost:,.0f} | ${nets[a]:,.0f} | ${dr.net(c, c_false=0) / n:,.0f} | ${dr.net(c, c_false=10000) / n:,.0f} | {be} |")
        best = max(nets, key=nets.get)
        L += ["", f"Best net per seed: {best} (${nets[best]:,.0f}).", ""]
    L += ["## Reading", "",
          "- Compare arms within a table only; seeds and data differ between tables.",
          "- An arm below $0 loses money against asking nobody at these prices and this scale; the dollar score rewards asking only where the documented recovery pays for the asking.",
          "- Break-even scale: how many times larger the values would have to be (a bigger real practice, a longer look-back) for the arm to break even."]
    open(os.path.join(ROOT, "docs", "release5_dollar_baseline.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
