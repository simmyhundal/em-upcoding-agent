"""W2.5 as run in the release 5 fresh test (the writer called the model for rule-silent providers) against W2.5 re-run API-free (no_model: code-written inconclusive) on the same ten seeds.
Free. Writes docs/release5_w25_api_vs_free.md. Usage: python eval/compare_w25_api.py
"""
import json
import multiprocessing as mp
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import dev_release3 as dev  # noqa: E402
import dollar_reward as dr  # noqa: E402
import make_v2_office_workflow_runs as ow  # noqa: E402
import run_release2 as r2  # noqa: E402
import run_release5 as r5  # noqa: E402


def rerun(seed):
    rid, code = f"r5w25n_{seed}", f"r5_{seed}"
    if not r2.done(rid, "case_summaries_checked.jsonl"):
        ow.run(rid, code, dev.write_flagged(code, "eb_ratio_t", 10), r5.NOTE.format(s=seed) + "; workflow W2.5 API-free", version="2.5", tier1_n=r5.TIER1_N)
    return seed


def usd(pre, seed):
    f = os.path.join(ROOT, "experiments", f"{pre}_{seed}", "usage_writer.jsonl")
    return sum(json.loads(l).get("estimated_usd", 0) for l in open(f)) if os.path.exists(f) else 0.0


def main():
    with mp.Pool(4) as pool:
        pool.map(rerun, r5.SEEDS)
    n = len(r5.SEEDS)
    rows = {}
    for name, pre in (("W2.5 with API calls (as tested)", "r5w25"), ("W2.5 API-free", "r5w25n")):
        comp = [dr.from_run(f"{pre}_{s}", f"r5_{s}") for s in r5.SEEDS]
        t = dr.add(comp)
        calls = sum(1 for s in r5.SEEDS for l in open(os.path.join(ROOT, "experiments", f"{pre}_{s}", "case_summaries_checked.jsonl")) if json.loads(l).get("source", "").startswith("llm"))
        rows[name] = (comp, t, calls, sum(usd(pre, s) for s in r5.SEEDS))
    L = ["# W2.5 with API calls against W2.5 API-free (release 5 fresh seeds)", "", "[Back to the README](../README.md)", "",
         "Generated by `python eval/compare_w25_api.py`. Free. Same ten fresh seeds (4545 to 5454), same office, same policy file; the only difference is the writer for providers where the rules are silent: "
         "the first row had the model (Opus 5.5, Batch API) write the summary, the second has code write it as inconclusive. Net dollars as in [release5_results.md](release5_results.md).", "",
         "| Version | Model-written summaries | Writer cost | Upcoders found | Honest doctors called | Value | Costs | **Net $ per seed** | Net, charge $0 | Net, charge $10,000 |", "|---|---|---|---|---|---|---|---|---|---|"]
    for name, (comp, t, calls, c) in rows.items():
        cost = dr.C_COPY * t["all_rounds"] + dr.C_BURDEN * t["honest_rounds"] + dr.C_REVIEW * t["reviewed"] + dr.C_FALSE * t["honest_called"]
        L.append(f"| {name} | {calls} | ${c:.3f} | {t['found']} of {t['upcoders']} | {t['honest_called']} | ${t['value']:,.0f} | ${cost:,.0f} | **${dr.net(t) / n:,.0f}** | ${dr.net(t, c_false=0) / n:,.0f} | ${dr.net(t, c_false=10000) / n:,.0f} |")
    a, b = rows["W2.5 with API calls (as tested)"][0], rows["W2.5 API-free"][0]
    diff = [(s, dr.net(y) - dr.net(x)) for s, x, y in zip(r5.SEEDS, a, b) if abs(dr.net(y) - dr.net(x)) > 0.5]
    L += ["", "Seeds where the two differ: " + (", ".join(f"{s} (${d:,.0f})" for s, d in diff) if diff else "none") + "."]
    open(os.path.join(ROOT, "docs", "release5_w25_api_vs_free.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
