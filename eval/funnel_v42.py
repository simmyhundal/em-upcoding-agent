"""The release funnel for workflow v4.2 on the ten data 4.2 test seeds (docs/funnel_v42.md): where providers drop out between the population and a demand, for the two lanes separately. Free; reads
stored runs and, for the denominators only, the answer key (evaluation only). Usage: python eval/funnel_v42.py [--write]"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import d42_truth as dt  # noqa: E402
import dev_pool_v42 as pool  # noqa: E402
import score_42 as s42  # noqa: E402


def funnel(pre="d42t_h28_"):
    L = dict.fromkeys(["providers", "true_upcoders", "shortlisted", "shortlisted_true", "asked", "usable", "called", "withdrawn", "demanded", "demanded_true", "dollars"], 0)
    F = dict.fromkeys(["providers", "true_imp", "flagged", "requested", "answered", "eligible", "demanded", "dollars"], 0)
    for s in pool.TEST:
        code, rid = f"d42_{s}", f"{pre}{s}"
        key = dt.load_key(code)["providers"]
        r15 = {p for p, v in key.items() if v["net_rate"] >= 0.15}
        imp = {p for p, v in key.items() if v["true_overpay_fwa"].get("impossible_days", 0) > 0}
        L["providers"] += len(key); L["true_upcoders"] += len(r15); F["providers"] += len(key); F["true_imp"] += len(imp)
        recs = [json.loads(x) for x in open(os.path.join(ROOT, "experiments", rid, "case_summaries_checked.jsonl")) if x.strip()]
        short = {r["provider_id"] for r in recs}
        asked, usable = set(), set()
        for line in open(os.path.join(ROOT, "experiments", rid, "office_transcript.jsonl")):
            e = json.loads(line)
            if e.get("action") == "send_request":
                asked.add(e["provider_id"])
            if e.get("usable_total", 0) > 0:
                usable.add(e["provider_id"])
        withdrawn = set(json.load(open(os.path.join(ROOT, "experiments", rid, "demand_floor.json")))["withdrawn"])
        called = {r["provider_id"] for r in recs if r["summary"]["leaning"] == "pattern_consistent_with_upcoding"}
        L["shortlisted"] += len(short); L["shortlisted_true"] += len(short & r15); L["asked"] += len(asked); L["usable"] += len(usable)
        L["withdrawn"] += len(withdrawn); L["called"] += len(called | withdrawn); L["demanded"] += len(called); L["demanded_true"] += len(called & r15)
        ln = s42.lane(rid)["providers"]
        F["flagged"] += len(ln); F["requested"] += len(ln)
        F["answered"] += sum(1 for v in ln.values() if v["estimate"]["mode"] != "none")
        F["eligible"] += sum(1 for v in ln.values() if v["estimate"]["value"] >= v["demand_cost"])
        F["demanded"] += sum(1 for v in ln.values() if v["demand"])
        c, _ = s42.seed_result(rid, code)
        L["dollars"] += c["recovered_level"]; F["dollars"] += c["recovered_fwa"]
    return L, F


def markdown():
    L, F = funnel()
    return f"""# The release funnel for workflow v4.2

[Back to the README](../README.md) · [test result](v42_test_result.md) · [concepts](concepts/README.md)

**What this page is.** Where providers drop out between the whole population and a demand, on the ten data 4.2 test seeds (2,160 providers), for the two ways a provider can be found: the level review and the [volume screen](concepts/volume-screen.md). Generated by `python eval/funnel_v42.py --write`. Counts are providers summed over the ten seeds.

## Level review (billing a visit above its level)
| Stage | Providers |
|---|---|
| In the ten datasets | {L['providers']:,} |
| True upcoders (true net level rate of 15% or more) | {L['true_upcoders']} |
| [Shortlisted](concepts/shortlist.md) by the screen (4 per seed) | {L['shortlisted']}, of which {L['shortlisted_true']} true upcoders |
| Asked for charts by the [request recommendation](concepts/request-recommendation.md) | {L['asked']} |
| Returned at least one usable chart | {L['usable']} |
| Called upcoding by the chart rules | {L['called']} |
| Demand-eligible (the conservative estimate covers a demand; the [break-even rule](concepts/break-even-rule.md) withdrew {L['withdrawn']}) | {L['demanded']} |
| Demanded, of which true upcoders | {L['demanded']}, of which {L['demanded_true']} |
| Recovered | ${L['dollars']:,.0f} |

## Volume screen (billing visits that never happened)
| Stage | Providers |
|---|---|
| In the ten datasets | {F['providers']:,} |
| With impossible-day billing | {F['true_imp']} |
| Flagged by the volume screen and requested | {F['flagged']} |
| Office gave something usable (a chart or "no record") | {F['answered']} |
| Demand-eligible | {F['eligible']} |
| Demanded | {F['demanded']} |
| Recovered | ${F['dollars']:,.0f} |

## Reading it
The two largest losses in the level review are the shortlist cap (of {L['true_upcoders']} true upcoders only {L['shortlisted_true']} reach the shortlist of {L['shortlisted']}) and the request recommendation (half of the shortlisted providers are not asked), followed by the break-even rule ({L['called']} called, {L['demanded']} demanded). Shortlisting more costs triage and chart review on providers who are mostly not upcoders; that trade is what the list-size experiments measured. The volume screen loses providers only where the office stays silent. Of the {L['demanded']} level demands, all {L['demanded_true']} are true upcoders: the review is precise and has low reach.
"""


if __name__ == "__main__":
    md = markdown()
    if "--write" in sys.argv:
        open(os.path.join(ROOT, "docs", "funnel_v42.md"), "w").write(md)
    print(md)
