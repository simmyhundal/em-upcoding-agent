"""Release 5 fresh test, one look (issue 109): W2.3, GL, W2.5 and agent v3.5 on seeds 4545 to 5454, scored in net dollars (eval/dollar_reward.py: option 2, 90% lower bound).
Writes docs/release5_results.md and experiments/release5_results.json. Free. Usage: python eval/analyze_release5.py
"""
import json
import os
import statistics as st
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import dollar_reward as dr  # noqa: E402

SEEDS = [4545, 4646, 4747, 4848, 4949, 5050, 5151, 5252, 5353, 5454]
ARMS = [("W2.3", "r5w23"), ("GL", "r5gl"), ("W2.5", "r5w25"), ("A3.5", "r5a")]


def main():
    comp = {a: [dr.from_run(f"{pre}_{s}", f"r5_{s}") for s in SEEDS] for a, pre in ARMS}
    tot = {a: dr.add(c) for a, c in comp.items()}
    L = ["# Release 5 fresh test: results (issue 109)", "", "[Back to the README](../README.md)", "",
         "Generated by `python eval/analyze_release5.py`. Ten fresh seeds (4545 to 5454, step 101), data 2.2, 216 doctors, 8 planted upcoders each (80 in all). **Score: net dollars** "
         "(recovery option 2, 90% lower bound, $90 per round, $43.84 per round to an honest practice, $158 per practice reviewed, $2,000 per honest doctor called; sources and caveats in "
         "`eval/dollar_reward.py`). One look; policies frozen before the seeds were generated (pre-registration on issue 109). Dollars are a ranking at the simulated scale, option 2 is the "
         "optimistic recovery model, and the $2,000 charge is an assumption.", "",
         "| Arm | Upcoders found | Recall | Honest doctors called | Value | Costs | **Net $ per seed** | Net, charge $0 | Net, charge $10,000 | Net, option 1 | Break-even scale |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    n = len(SEEDS)
    for a, _ in ARMS:
        t = tot[a]
        net = dr.net(t)
        cost = dr.C_COPY * t["all_rounds"] + dr.C_BURDEN * t["honest_rounds"] + dr.C_REVIEW * t["reviewed"] + dr.C_FALSE * t["honest_called"]
        L.append(f"| {a} | {t['found']} of {t['upcoders']} | {t['found'] / t['upcoders']:.0%} | {t['honest_called']} | ${t['value']:,.0f} | ${cost:,.0f} | **${net / n:,.0f}** | "
                 f"${dr.net(t, c_false=0) / n:,.0f} | ${dr.net(t, c_false=10000) / n:,.0f} | ${dr.net(t, value_key='value_downcode') / n:,.0f} | {cost / max(t['value'], 1):.1f}x |")
    L += ["", "## Net dollars by seed", "", "| Seed | " + " | ".join(a for a, _ in ARMS) + " |", "|---|" + "---|" * len(ARMS)]
    for i, s in enumerate(SEEDS):
        L.append(f"| {s} | " + " | ".join(f"${dr.net(comp[a][i]):,.0f}" for a, _ in ARMS) + " |")
    d = [dr.net(comp["A3.5"][i]) - dr.net(comp["W2.5"][i]) for i in range(n)]
    d2 = [dr.net(comp["W2.5"][i]) - dr.net(comp["GL"][i]) for i in range(n)]
    L += ["", f"Paired by seed: A3.5 minus W2.5 averages ${st.mean(d):,.0f} per seed (range ${min(d):,.0f} to ${max(d):,.0f}; A3.5 ahead on {sum(x > 0 for x in d)} of {n}). "
          f"W2.5 minus GL averages ${st.mean(d2):,.0f} (range ${min(d2):,.0f} to ${max(d2):,.0f}; ahead on {sum(x > 0 for x in d2)} of {n}). Ten seeds of eight upcoders: gaps under about one seed's spread are not confirmed.", ""]
    adv = [json.load(open(os.path.join(ROOT, "experiments", f"r5a_{s}", "advice_log.json"))) for s in SEEDS]
    acts = sum(a["summary"]["actions"] for a in adv)
    withadv = sum(a["summary"]["with_advice"] for a in adv)
    fol = sum(a["summary"]["followed"] for a in adv)
    ov = sum(a["summary"]["overrides"] for a in adv)
    L += ["## What the agent did with the advice", "", f"- Records actions: {acts}; with advice on record: {withadv}; followed: {fol} ({fol / max(withadv, 1):.0%}). Overrides of a binding upcoding call: {ov}.",
          f"- Agent cost: ${sum(json.load(open(os.path.join(ROOT, 'experiments', f'r5a_results_{s}.json')))['cost_usd'] for s in SEEDS):.2f} for ten runs (cap $5)."]
    open(os.path.join(ROOT, "docs", "release5_results.md"), "w").write("\n".join(L) + "\n")
    json.dump({a: {"per_seed": [dr.net(c) for c in comp[a]], **tot[a]} for a, _ in ARMS}, open(os.path.join(ROOT, "experiments", "release5_results.json"), "w"), indent=1)
    print("\n".join(L))


if __name__ == "__main__":
    main()
