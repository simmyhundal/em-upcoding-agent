"""Free replay of the stored A3.4 runs of the release 4 test (r4a_*) under the v3.5 binding rule (issue 112).

Each run's records requests are replayed in order against a fresh office inside a v3.5 Environment, hybrid_review is run on the providers the agent reviewed (no model: only rule-decided
leanings bind), and the findings the agent submitted are checked: how many differ from a rule-decided leaning and would have been refused without an override_reason, and who they were
(answer key, eval only). Writes docs/release5_binding_replay.md. No model calls.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import agent_tools as at  # noqa: E402
import run_agent  # noqa: E402

SEEDS = list(range(3535, 4445, 101))
UP = "pattern_consistent_with_upcoding"


def replay(seed):
    code, rid = f"r4_{seed}", f"r4a_{seed}"
    data = os.path.join(ROOT, "data", f"synthetic_v2_{code}")
    env = at.Environment(data, os.path.join(data, "view"), seed=1, records_budget=run_agent.EVAL_RECORDS_BUDGET_33, version="3.5")
    key = json.load(open(os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_{code}.json")))["providers"]
    submitted, reviewed = [], []
    for line in open(os.path.join(ROOT, "experiments", rid, "audit.jsonl")):
        a = json.loads(line)
        args = a["args"]
        if a["tool"] in ("request_records", "follow_up_records", "close_records", "request_audit_trail"):
            env.call(a["tool"], args)
        elif a["tool"] == "hybrid_review":
            env.call("hybrid_review", args)
            reviewed += args["provider_ids"]
        elif a["tool"] == "submit_findings":
            submitted = args["findings"]
    rows = []
    for f in submitted:
        pid, lean = f["provider_id"], f["leaning"]
        rule = env.rule_result.get(pid)
        if rule and rule[1] in ("summary_rule", "chart_rule") and rule[0] != lean:
            rows.append({"seed": seed, "provider": pid, "agent": lean, "rules": rule[0], "source": rule[1], "role": key[pid]["role"]})
    return rows, len(submitted), sum(1 for f in submitted if (env.rule_result.get(f["provider_id"]) or (0, ""))[1] in ("summary_rule", "chart_rule"))


def main():
    allrows, nsub, nrule = [], 0, 0
    for s in SEEDS:
        r, n, k = replay(s)
        allrows += r
        nsub += n
        nrule += k
    L = ["# Release 5: what the binding rule would have refused in the stored A3.4 runs (issue 112)", "", "[Back to the README](../README.md)", "",
         "Generated by `python eval/replay_binding_35.py`. Free: the ten stored agent v3.4 runs of the release 4 test are replayed against a fresh office in an agent v3.5 environment, "
         "hybrid_review is run on the providers the agent reviewed (rules only, no model), and the submitted findings are compared with the rule-decided leanings. Answer key used only to label results.", "",
         f"- Findings submitted: {nsub}; of these, {nrule} had a rule-decided leaning (summary rule or chart rule) on the replayed records.",
         f"- Findings that differ from a rule-decided leaning, and so would be refused without an `override_reason`: **{len(allrows)}**.", "",
         "| Seed | Provider | Rules said | Agent wrote | Rule source | Truth |", "|---|---|---|---|---|---|"]
    for r in allrows:
        L.append(f"| {r['seed']} | {r['provider']} | {r['rules']} | {r['agent']} | {r['source']} | {r['role']} |")
    up_missed = sum(r["role"] == "upcoder" and r["rules"] == UP for r in allrows)
    hon_saved = sum(r["role"] != "upcoder" and r["agent"] != UP and r["rules"] == UP for r in allrows)
    L += ["", f"Of these, {up_missed} are upcoders the rules called and the agent did not (binding would have added them); {hon_saved} are honest doctors the rules called upcoding and the agent did not "
          "(binding would have called them). Net effect of binding with no overrides: see the two counts.", "",
          "Caveat: replayed records equal what the agent saw (the office is deterministic); the agent's actions might differ if it had seen binding rules."]
    open(os.path.join(ROOT, "docs", "release5_binding_replay.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
