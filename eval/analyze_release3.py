"""Release 3 evaluation analysis (issue 99), fixed BEFORE any fresh seed was generated.

Pre-registered rule (posted on issue 99 before the first fresh seed):
- Seeds 2525, 2626, 2727, 2828, 2929, 3030, 3131, 3232, 3333, 3434 (data 2.2, 216 doctors, 8 planted upcoders, 8 hard negatives, half clone notes). ONE look, at all
  ten seeds; no interim tests. Fewer than ten completed: descriptive only.
- Unit and test as in release 2 (analyze_release2.py): an arm "finds" a planted upcoder when its final summary leans upcoding; McNemar on the upcoders found by
  only one arm, z = (b - c) / sqrt(1.5 (b + c)) (design effect 1.5 for seeds as clusters), two-sided, with the exact McNemar p beside it.
- Two pre-specified comparisons, each at alpha 0.025 (0.05 shared over two):
    PRIMARY    workflow v2.3 against agent v3.3 (does the workflow stay ahead of the agent?)
    SECONDARY  workflow v2.3 against workflow v2.2 on the same seeds (did the release 3 changes help?)
  The agent's change from 3.2 to 3.3 is not tested (release 2 used other seeds); it is described only.
- Reported, never a stopping rule: honest doctors called, honest practices asked, request rounds, cost, found per seed with a paired bootstrap interval.
- Cap $5 for the batch (estimate $2.5). The rule judge is not run (j3.2 predates rules 2.3).

Usage: python eval/analyze_release3.py [--write]      # --write writes docs/release3_results.md
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "eval"))
from analyze_release2 import bootstrap, called, cost, p_exact, p_z  # noqa: E402

SEEDS = [2525, 2626, 2727, 2828, 2929, 3030, 3131, 3232, 3333, 3434]
ALPHA, CAP_USD = 0.025, 5.0
ARMS = (("w2", "r3w2", "workflow v2.2"), ("w3", "r3w", "workflow v2.3"), ("a3", "r3a", "agent v3.3"))


def burden(rid, key):
    rounds, asked = 0, set()
    for line in open(os.path.join(ROOT, "experiments", rid, "office_transcript.jsonl")):
        e = json.loads(line)
        if e.get("action") in ("send_request", "follow_up") and "error" not in e and key[e["provider_id"]]["role"] != "upcoder":
            rounds += 1
            asked.add(e["provider_id"])
    return len(asked), rounds


def load():
    out = []
    for seed in SEEDS:
        key_path = os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_r3_{seed}.json")
        ok = os.path.exists(key_path) and all(os.path.exists(os.path.join(ROOT, "experiments", f"{pre}_{seed}", "case_summaries_checked.jsonl")) for _, pre, _ in ARMS)
        if not ok:
            continue
        key = json.load(open(key_path))["providers"]
        up = {p for p, v in key.items() if v["role"] == "upcoder"}
        r = {"seed": seed, "upcoders": len(up)}
        for tag, pre, _ in ARMS:
            c = called(f"{pre}_{seed}")
            r[tag] = c & up
            r[tag + "_found"], r[tag + "_honest"] = len(c & up), len(c - up)
            r[tag + "_asked"], r[tag + "_rounds"] = burden(f"{pre}_{seed}", key)
            r[tag + "_cost"] = cost(f"{pre}_{seed}")
        out.append(r)
    return out


def compare(rows, x, y):
    b = sum(len(r[x] - r[y]) for r in rows)
    c = sum(len(r[y] - r[x]) for r in rows)
    return b, c, p_z(b, c), p_exact(b, c)


def report(rows):
    n = len(rows)
    spent = sum(r[t + "_cost"] for r in rows for t, _, _ in ARMS)
    L = ["# Release 3 evaluation: workflow v2.3 and agent v3.3 on fresh seeds (issue 99)", "", "[Back to the README](../README.md)", "",
         "Generated by `python eval/analyze_release3.py --write`; the rule is in the script's docstring and was posted on issue 99 before any seed was generated. "
         f"Seeds completed: {n} of {len(SEEDS)}. Spent: ${spent:.2f} of ${CAP_USD:.0f} (estimated from list prices). Data 2.2, as release 2.", "",
         "| Seed | Upcoders | W2.2 found | W2.3 found | A3.3 found | Honest called (W2.2 / W2.3 / A3.3) | Honest practices asked (W2.2 / W2.3 / A3.3) | Cost (W2.2 / W2.3 / A3.3) |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['seed']} | {r['upcoders']} | {r['w2_found']} | {r['w3_found']} | {r['a3_found']} | {r['w2_honest']} / {r['w3_honest']} / {r['a3_honest']} | "
                 f"{r['w2_asked']} / {r['w3_asked']} / {r['a3_asked']} | ${r['w2_cost']:.2f} / ${r['w3_cost']:.2f} / ${r['a3_cost']:.2f} |")
    s = lambda k: sum(r[k] for r in rows)
    L += [f"| **Total** | {s('upcoders')} | {s('w2_found')} | {s('w3_found')} | {s('a3_found')} | {s('w2_honest')} / {s('w3_honest')} / {s('a3_honest')} | "
          f"{s('w2_asked')} / {s('w3_asked')} / {s('a3_asked')} | ${s('w2_cost'):.2f} / ${s('w3_cost'):.2f} / ${s('a3_cost'):.2f} |", ""]
    if rows:
        L += [f"Request rounds on honest practices: W2.2 {s('w2_rounds')}, W2.3 {s('w3_rounds')}, A3.3 {s('a3_rounds')}.", ""]
        for a, b, label in (("w3", "a3", "W2.3 minus A3.3"), ("w3", "w2", "W2.3 minus W2.2")):
            m, lo, hi = bootstrap([r[a + "_found"] - r[b + "_found"] for r in rows], seed=99)
            L.append(f"{label}, upcoders found per seed: {m:+.2f} (95% bootstrap interval {lo:+.2f} to {hi:+.2f} over {n} seeds).")
        L.append("")
    final = n == len(SEEDS)
    for x, y, name in (("w3", "a3", "PRIMARY, workflow v2.3 against agent v3.3"), ("w3", "w2", "SECONDARY, workflow v2.3 against workflow v2.2")):
        if not rows:
            break
        b, c, pz, pe = compare(rows, x, y)
        first, second = {"w3": "workflow v2.3", "a3": "agent v3.3", "w2": "workflow v2.2"}[x], {"w3": "workflow v2.3", "a3": "agent v3.3", "w2": "workflow v2.2"}[y]
        if final:
            L.append(f"**{name}:** found only by {first}: {b}; only by {second}: {c}; z-test with design effect 1.5: p = {pz:.4f} against alpha {ALPHA} "
                     f"({'significant' if pz <= ALPHA else 'not significant'}); exact McNemar p = {pe:.4f}.")
        else:
            L.append(f"**{name}** (descriptive only until all {len(SEEDS)} seeds are done): only {first} {b}, only {second} {c}.")
    if rows:
        L += ["", "## Reading", "",
              f"- **Found per arm:** W2.2 {s('w2_found')} of {s('upcoders')}, W2.3 {s('w3_found')}, A3.3 {s('a3_found')}. The workflow changes helped on these fresh seeds about as much as on the development seeds "
              "(38 of 78 in sample against the held-out result above), which is some evidence they were not fitted to the development data.",
              f"- **Honest burden:** W2.3 sent requests to {s('w3_asked')} honest practices against {s('w2_asked')} for W2.2 and {s('a3_asked')} for A3.3 (request rounds {s('w3_rounds')}, {s('w2_rounds')}, {s('a3_rounds')}). "
              "The wider list is where the extra upcoders come from, and it is what costs the practices; A3.3 found nearly as many with about half of W2.3's honest requests.",
              f"- **False accusations:** {s('w2_honest')} honest doctors called by W2.2, {s('w3_honest')} by W2.3, {s('a3_honest')} by A3.3.",
              "- **Cost:** the workflows cost about a cent a seed; the agent about $0.23 a seed.",
              "- **Limits:** one data version (2.2) and generated notes, so cloned-notes signs are probably easier than real ones; the agent ran at low effort; ten seeds is a small sample. "
              "The agent's gain over release 2 (A3.2 found 12 of 78 on other seeds) is not a paired result.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    t = report(load())
    print(t)
    if "--write" in sys.argv:
        open(os.path.join(ROOT, "docs", "release3_results.md"), "w").write(t + "\n")
