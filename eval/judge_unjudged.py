"""Run the free rule judge on every stored run that has summaries but no rule-judge output yet, and write docs/judge_unjudged.md. Free, deterministic, no model.

Runs on data 2.2 (release 3 onward: rules 2.3, d3a, r4*, r5*) get j3.3 (`eval/judge_rules_33.py`, writes usefulness_rules_33.jsonl) with the frozen j3.2 beside it; the older
registry runs are listed with the reason when no rule judge applies. A run is skipped when any usefulness_rules*.jsonl exists. Usage: python eval/judge_unjudged.py
"""
import collections
import json
import os
import re
import statistics as st
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import judge_rules_32 as j32  # noqa: E402
import judge_rules_33 as j33  # noqa: E402

EXP = os.path.join(ROOT, "experiments")
ARM_NAMES = {"r4w23": "W2.3", "r4g": "G", "r4l": "L", "r4gl": "GL", "r4a": "A3.4", "r5w23": "W2.3", "r5gl": "GL", "r5w25": "W2.5", "r5a": "A3.5", "d3a": "A3.3 smoke"}


def code_of(rid):
    m = re.match(r"^(r\d)[a-z0-9]*_(\d+)$", rid)
    return f"{m.group(1)}_{m.group(2)}" if m else None


def pending():
    out = []
    for rid in sorted(os.listdir(EXP)):
        d = os.path.join(EXP, rid)
        if os.path.isfile(os.path.join(d, "case_summaries_checked.jsonl")) and not any(f.startswith("usefulness_rules") for f in os.listdir(d)):
            out.append(rid)
    return out


def main():
    todo = pending()
    rows, skipped = collections.defaultdict(list), []
    for rid in todo:
        code = code_of(rid)
        pre = rid.rsplit("_", 1)[0]
        view = os.path.join(ROOT, "data", f"synthetic_v2_{code}", f"view_{rid}") if code else None
        flagged = os.path.join(EXP, code, "flagged.csv") if code else None
        if pre not in ARM_NAMES or not (view and os.path.isdir(view) and os.path.exists(flagged)):
            skipped.append((rid, "no data 2.2 view or flagged file; the 2.2 rule judge does not apply" if pre not in ARM_NAMES else "view or flagged file missing"))
            continue
        summ, run_dir = os.path.join(EXP, rid, "case_summaries_checked.jsonl"), os.path.join(EXP, rid)
        new = j33.run(view, flagged, summ, os.path.join(run_dir, "usefulness_rules_33.jsonl"), run_dir=run_dir)
        old = j32.run(view, flagged, summ, "/tmp/_j32.jsonl", run_dir=run_dir)
        lean = {x["provider_id"]: x["summary"]["leaning"] for x in map(json.loads, open(summ))}
        for a, b in zip(new, old):
            rows[pre].append({"lean": lean[a["provider_id"]], "s33": a["score"], "s32": b["score"]})
    L = ["# Rule judge on runs that had none (j3.3, with j3.2 beside it)", "", "[Back to the README](../README.md)", "",
         "Generated by `python eval/judge_unjudged.py`. Free and deterministic. The judge's thresholds are rules 2.3's own, so it is not independent of the writer, and no person has checked it "
         "([human_spot_check.md](human_spot_check.md)).", "",
         "| Arm (run prefix) | Runs | Summaries | Mean j3.3 | Mean j3.2 | Upcoding calls | Mean j3.3 on them |", "|---|---|---|---|---|---|---|"]
    for pre in sorted(rows):
        r = rows[pre]
        up = [x for x in r if x["lean"] == "pattern_consistent_with_upcoding"]
        mean_up = f"{st.mean(x['s33'] for x in up):.2f}" if up else "-"
        n = len([1 for rid in todo if rid.rsplit("_", 1)[0] == pre])
        L.append(f"| {ARM_NAMES[pre]} ({pre}) | {n} | {len(r)} | {st.mean(x['s33'] for x in r):.2f} | {st.mean(x['s32'] for x in r):.2f} | {len(up)} | "
                 f"{mean_up} |")
    if skipped:
        L += ["", "Runs left unjudged:", ""] + [f"- `{rid}`: {why}" for rid, why in skipped]
    open(os.path.join(ROOT, "docs", "judge_unjudged.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
