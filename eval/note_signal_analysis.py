"""How detectable are cloned notes in data v2.1? A free, no-model look at the per-provider signals (issue 57). Development seed only.

Generates data v2.1 for the development seed at three clone-signal strengths, draws 30 notes per provider, computes the claim-versus-note
signals (src/note_checks.py) and reports, per signal, the mean rate for cloners, upcoders with honest notes, and everyone else, plus how
well the rate separates cloners from non-cloners (AUC: 0.5 = no better than chance, 1.0 = perfect). Writes docs/note_signals.md.
The thresholds in note_checks.py were fixed before this run; nothing is tuned on these results.

Usage:
    python eval/note_signal_analysis.py
"""
import csv
import json
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
import derive  # noqa: E402
import generate_v2 as g  # noqa: E402
import note_checks as nc  # noqa: E402

SEED = 42
STRENGTHS = [0.7, 0.3, 0.0]


def auc(pos, neg):
    pairs = [(p, n) for p in pos for n in neg]
    if not pairs:
        return float("nan")
    return sum(1.0 if p > n else 0.5 if p == n else 0.0 for p, n in pairs) / len(pairs)


def analyse(strength):
    tag = f"s{SEED}_str{int(strength * 100)}"
    data = os.path.join(ROOT, "data", f"synthetic_v21_{tag}")
    key = os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v21_{tag}.json")
    g.build(data, key, seed=SEED, n_providers=216, n_upcoders=8, n_hard_neg=8, clone_share=0.5, data_version="2.1", clone_signal_strength=strength)
    view = os.path.join(data, "view")
    derive.build_view(data, view)
    truth = json.load(open(key))["providers"]
    claims = {r["claim_id"]: r for r in csv.DictReader(open(os.path.join(view, "claims.csv")))}
    notes = nc.load_notes(data)
    by_prov = {}
    for cid, c in claims.items():
        by_prov.setdefault(c["provider_id"], []).append(cid)
    rng = random.Random(f"signals:{SEED}")
    rows = {}
    for pid, ids in by_prov.items():
        pick = rng.sample(sorted(ids), min(30, len(ids)))
        rows[pid] = nc.provider_signals([(notes[c], claims[c]) for c in pick if c in notes], with_audit=True)
    return truth, rows


def group(t):
    if t["role"] == "upcoder":
        return "cloner" if t["clones_notes"] else "upcoder_honest_notes"
    return "honest_template" if t.get("uses_template") else "honest_varied"


def main():
    out = ["# Cloned-note signals in data v2.1 (development seed 42)", "",
           "Generated by `python eval/note_signal_analysis.py`. A free analysis: 30 notes per provider drawn at random, the claim-versus-note checks "
           "of `src/note_checks.py`, thresholds fixed in advance. Rates are the share of a provider's returned notes that show the signal "
           "(time_repeat: the share of notes with the modal minutes figure; duplicate: the share with a near-duplicate note for a different patient). "
           "AUC separates the 4 cloning providers from all 208 non-cloners (0.5 is chance). Four cloners is a small sample; read the AUCs as "
           "rough. The audit-trail signals need a second-tier request.", ""]
    for strength in STRENGTHS:
        truth, rows = analyse(strength)
        out += [f"## Clone signal strength {strength}", "", "| Signal | cloners | upcoders, honest notes | honest, fixed template | honest, varied | AUC (cloners vs the rest) |", "|---|---|---|---|---|---|"]
        for sig in nc.SIGNALS:
            means, pos, neg = {}, [], []
            for pid, r in rows.items():
                v = r[sig]
                if v is None:
                    continue
                grp = group(truth[pid])
                means.setdefault(grp, []).append(v)
                (pos if grp == "cloner" else neg).append(v)
            cell = lambda k: f"{sum(means[k]) / len(means[k]):.2f}" if means.get(k) else "–"
            out.append(f"| {sig} | {cell('cloner')} | {cell('upcoder_honest_notes')} | {cell('honest_template')} | {cell('honest_varied')} | {auc(pos, neg):.2f} |")
        out.append("")
    out += ["**Reading.** Where AUC is near 0.5 the signal does not help; near 1.0 it separates cloners from everyone else. Fixed-template honest "
            "providers are the control for the similarity signals: they copy too, so duplicates alone are not evidence.", ""]
    open(os.path.join(ROOT, "docs", "note_signals.md"), "w").write("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
