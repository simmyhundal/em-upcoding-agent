"""Release 2 evaluation analysis (issue 90): workflow v2.2 against agent v3.2, paired by upcoder, with the looks fixed BEFORE any batch ran.

Pre-registered rule (posted on issue 90 before the first batch):
- Unit: each planted-and-counted upcoder (the answer key's role "upcoder"); an arm "finds" it when the arm's final summary for that provider leans
  pattern_consistent_with_upcoding. Both arms run on the same data, same screen (eb_ratio, top 5%), same seed.
- Test: McNemar on the upcoders only one arm found (b = workflow only, c = agent only), z = (b - c) / sqrt(DEFF (b + c)) with DEFF = 1.5 for seeds as
  clusters; two-sided p. The exact McNemar p-value is reported beside it. Looks at LOOKS seeds (22 and 44), each at alpha = 0.0294 (two looks share 0.05);
  fewer seeds than the first look: descriptive only, no test is applied. If the budget (CAP_USD) is spent first, the final look uses the seeds completed.
- Also reported (never a stopping rule): honest doctors called by each arm, records burden (honest practices asked), cost, found per seed with a
  95% paired bootstrap interval over seeds.

Usage:
    python eval/analyze_release2.py [--write]      # --write writes docs/release2_results.md
"""
import glob
import json
import math
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFF, ALPHA, LOOKS, CAP_USD = 1.5, 0.0294, (22, 44), 10.0


def p_z(b, c, deff=DEFF):
    n = b + c
    if n == 0:
        return 1.0
    return math.erfc(abs(b - c) / math.sqrt(deff * n) / math.sqrt(2))


def p_exact(b, c):
    n, k = b + c, min(b, c)
    if n == 0:
        return 1.0
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)


def bootstrap(diffs, n=10000, seed=90):
    rng = random.Random(seed)
    means = sorted(sum(rng.choice(diffs) for _ in diffs) / len(diffs) for _ in range(n))
    return sum(diffs) / len(diffs), means[int(0.025 * n)], means[int(0.975 * n) - 1]


def cost(rid):
    d = os.path.join(ROOT, "experiments", rid)
    usd = 0.0
    for f in glob.glob(os.path.join(d, "usage_*.jsonl")):
        usd += sum(json.loads(x).get("estimated_usd", 0) for x in open(f) if x.strip())
    p = os.path.join(d, "agent_run.json")
    if os.path.exists(p):
        usd += json.load(open(p)).get("estimated_usd", 0)
    return usd


def called(rid):
    return {x["provider_id"] for x in map(json.loads, open(os.path.join(ROOT, "experiments", rid, "case_summaries_checked.jsonl")))
            if x["summary"]["leaning"] == "pattern_consistent_with_upcoding"}


def load(seeds=None):
    out = []
    for w in sorted(glob.glob(os.path.join(ROOT, "experiments", "r2w_[0-9]*"))):
        seed = int(os.path.basename(w).split("_")[1])
        a = os.path.join(ROOT, "experiments", f"r2a_{seed}")
        key_path = os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_r2_{seed}.json")
        if (seeds and seed not in seeds) or not os.path.exists(os.path.join(a, "case_summaries_checked.jsonl")) or not os.path.exists(key_path):
            continue
        key = json.load(open(key_path))["providers"]
        up = {p for p, v in key.items() if v["role"] == "upcoder"}
        cw, ca = called(f"r2w_{seed}"), called(f"r2a_{seed}")
        asked = lambda rid: len({p for p in (json.loads(l)["provider_id"] for l in open(os.path.join(ROOT, "experiments", rid, "office_transcript.jsonl")))
                                 if key[p]["role"] != "upcoder"})
        out.append({"seed": seed, "upcoders": len(up), "w_found": len(cw & up), "a_found": len(ca & up), "w_only": len((cw - ca) & up), "a_only": len((ca - cw) & up),
                    "both": len(cw & ca & up), "w_honest": len(cw - up), "a_honest": len(ca - up), "w_asked": asked(f"r2w_{seed}"), "a_asked": asked(f"r2a_{seed}"),
                    "w_cost": cost(f"r2w_{seed}"), "a_cost": cost(f"r2a_{seed}")})
    return out


def report(rows):
    n = len(rows)
    b, c = sum(r["w_only"] for r in rows), sum(r["a_only"] for r in rows)
    spent = sum(r["w_cost"] + r["a_cost"] for r in rows)
    lines = ["# Release 2 evaluation: workflow v2.2 against agent v3.2 (issue 90)", "", "[Back to the README](../README.md)", "",
             "**Superseded:** the ten-seed look below was not one of the pre-registered looks (22 and 44 seeds), so it carries no significance claim; the pre-registered fresh test of the next versions is [release3_results.md](release3_results.md) and found no significant gap between workflow and agent. "
             "Generated by `python eval/analyze_release2.py --write`; the rule is in the script's docstring and was posted on issue 90 before the first batch. "
             f"Seeds completed: {n}. Spent so far: ${spent:.2f} of ${CAP_USD:.0f} (estimated from list prices).", "",
             "| Seed | Upcoders | Workflow found | Agent found | Workflow only | Agent only | Honest called (W / A) | Honest practices asked (W / A) | Cost (W / A) |", "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['seed']} | {r['upcoders']} | {r['w_found']} | {r['a_found']} | {r['w_only']} | {r['a_only']} | {r['w_honest']} / {r['a_honest']} | "
                     f"{r['w_asked']} / {r['a_asked']} | ${r['w_cost']:.2f} / ${r['a_cost']:.2f} |")
    tw, ta = sum(r["w_found"] for r in rows), sum(r["a_found"] for r in rows)
    lines += [f"| **Total** | {sum(r['upcoders'] for r in rows)} | {tw} | {ta} | {b} | {c} | {sum(r['w_honest'] for r in rows)} / {sum(r['a_honest'] for r in rows)} | "
              f"{sum(r['w_asked'] for r in rows)} / {sum(r['a_asked'] for r in rows)} | ${sum(r['w_cost'] for r in rows):.2f} / ${sum(r['a_cost'] for r in rows):.2f} |", ""]
    if rows:
        m, lo, hi = bootstrap([r["a_found"] - r["w_found"] for r in rows])
        lines += [f"Agent minus workflow, upcoders found per seed: {m:+.2f} (95% bootstrap interval {lo:+.2f} to {hi:+.2f} over {n} seeds).", ""]
    look = max([k for k in LOOKS if n >= k], default=None)
    if look is None:
        lines += [f"**Status: descriptive only.** The first look is at {LOOKS[0]} seeds; with {n} no test is applied. "
                  f"Disagreement so far: {b} upcoders found only by the workflow, {c} only by the agent (exact McNemar p = {p_exact(b, c):.2f}, not a test result).", ""]
    else:
        pz = p_z(b, c)
        lines += [f"**Look at {look} seeds:** workflow only {b}, agent only {c}; z-test with design effect {DEFF}: p = {pz:.4f} against alpha {ALPHA} "
                  f"({'significant' if pz <= ALPHA else 'not significant'}); exact McNemar p = {p_exact(b, c):.4f}.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    rows = load()
    t = report(rows)
    print(t)
    if "--write" in sys.argv:
        open(os.path.join(ROOT, "docs", "release2_results.md"), "w").write(t + "\n")
