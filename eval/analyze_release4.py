"""Release 4 fresh-test analysis (issue 108), fixed BEFORE any fresh seed was generated.

Pre-registered rule (posted on issue 108 before the first fresh seed):
- Seeds 3535, 3636, 3737, 3838, 3939, 4040, 4141, 4242, 4343, 4444 (data 2.2, 216 doctors, 8 planted upcoders, 8 hard negatives, half clone notes). One look at all ten seeds;
  fewer completed: descriptive only. Workflow only, about $0.01 a seed; cap $1. No usefulness judge.
- Arms on every seed: W23 (workflow v2.3, the reference), G (light tier gated at ratio >= 2.5), L (learned stop-or-escalate policy, src/policy_24.json, lambda 0.05, whole list),
  GL (both).
- PRIMARY H1 (alpha 0.025): L finds more upcoders than W23. McNemar on the upcoders only one arm found, z = (b - c) / sqrt(1.5 (b + c)), two-sided; exact McNemar beside it.
- PRIMARY H2 (alpha 0.025): GL sends fewer rounds to honest practices than W23. Paired by seed; passes when the 97.5% bootstrap interval (10,000 resamples over seeds) of
  GL minus W23 lies below zero AND GL finds at least 90% of the upcoders W23 finds (total over the ten seeds) AND calls no more honest doctors than W23 plus one.
- Default for workflow v2.4: GL if H2 passes; else L if H1 passes; else G if it finds at least 90% of W23's upcoders with fewer honest rounds; else W23 stays.
- Reported, never a stopping rule: found, honest called, honest practices asked, rounds on honest practices per arm and seed; G and GL against W23 on upcoders found (descriptive).

Usage: python eval/analyze_release4.py [--write]      # --write writes docs/release4_results.md
"""
import json
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "eval"))
from analyze_release2 import called, cost, p_exact, p_z  # noqa: E402

SEEDS = [3535, 3636, 3737, 3838, 3939, 4040, 4141, 4242, 4343, 4444]
ARMS = ("W23", "G", "L", "GL")
ALPHA = 0.025


def burden(rid, key):
    rounds, asked = 0, set()
    for line in open(os.path.join(ROOT, "experiments", rid, "office_transcript.jsonl")):
        e = json.loads(line)
        if e.get("action") in ("send_request", "follow_up") and "error" not in e and key[e["provider_id"]]["role"] != "upcoder":
            rounds += 1
            asked.add(e["provider_id"])
    return len(asked), rounds


def boot(diffs, n=10000, seed=108):
    rng = random.Random(seed)
    m = sorted(sum(rng.choice(diffs) for _ in diffs) / len(diffs) for _ in range(n))
    return sum(diffs) / len(diffs), m[int(0.0125 * n)], m[int(0.9875 * n) - 1]


def load(prefix="r4", seeds=SEEDS, key_code="r4"):
    out = []
    for seed in seeds:
        kp = os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_{key_code}_{seed}.json")
        if not os.path.exists(kp) or not all(os.path.exists(os.path.join(ROOT, "experiments", f"{prefix}{a.lower()}_{seed}", "case_summaries_checked.jsonl")) for a in ARMS):
            continue
        key = json.load(open(kp))["providers"]
        up = {p for p, v in key.items() if v["role"] == "upcoder"}
        r = {"seed": seed, "upcoders": len(up)}
        for a in ARMS:
            rid = f"{prefix}{a.lower()}_{seed}"
            c = called(rid)
            r[a] = c & up
            r[a + "_found"], r[a + "_honest"] = len(c & up), len(c - up)
            r[a + "_asked"], r[a + "_rounds"] = burden(rid, key)
            r[a + "_cost"] = cost(rid)
        out.append(r)
    return out


def report(rows):
    n = len(rows)
    s = lambda k: sum(r[k] for r in rows)
    L = ["# Release 4 fresh test: workflow v2.4 variants against workflow v2.3 (issue 108)", "", "[Back to the README](../README.md)", "",
         f"Generated by `python eval/analyze_release4.py --write`; the rule is in the script's docstring and was posted on issue 108 before any seed was generated. Seeds completed: {n} of {len(SEEDS)}. "
         "Data 2.2. Workflow only.", "",
         "| Arm | Upcoders found | Honest doctors called | Honest practices asked | Rounds on honest practices | Cost |", "|---|---|---|---|---|---|"]
    names = {"W23": "W23 (workflow v2.3)", "G": "G (gate 2.5)", "L": "L (learned escalation)", "GL": "GL (gate and learned)"}
    for a in ARMS:
        L.append(f"| {names[a]} | {s(a + '_found')} of {s('upcoders')} | {s(a + '_honest')} | {s(a + '_asked')} | {s(a + '_rounds')} | ${s(a + '_cost'):.2f} |")
    if not rows:
        return "\n".join(L)
    final = n == len(SEEDS)
    b = sum(len(r["L"] - r["W23"]) for r in rows)
    c = sum(len(r["W23"] - r["L"]) for r in rows)
    L += ["", f"**H1, L against W23 on upcoders found:** only L {b}, only W23 {c}; z-test with design effect 1.5 p = {p_z(b, c):.4f}, exact McNemar p = {p_exact(b, c):.4f}"
          + (f" against alpha {ALPHA}: {'passes' if p_z(b, c) <= ALPHA and b > c else 'does not pass'}." if final else " (descriptive until all seeds are done).")]
    m, lo, hi = boot([r["GL_rounds"] - r["W23_rounds"] for r in rows])
    keep = s("GL_found") >= 0.9 * s("W23_found")
    safe = s("GL_honest") <= s("W23_honest") + 1
    h2 = hi < 0 and keep and safe
    L += [f"**H2, GL against W23 on rounds to honest practices:** {m:+.1f} per seed (97.5% interval {lo:+.1f} to {hi:+.1f}); GL finds {s('GL_found')} against {s('W23_found')} "
          f"({'at least' if keep else 'less than'} 90%); honest doctors called {s('GL_honest')} against {s('W23_honest')} ({'within' if safe else 'more than'} one)"
          + (f": {'passes' if h2 else 'does not pass'}." if final else " (descriptive until all seeds are done).")]
    for a in ("G", "GL"):
        x = sum(len(r[a] - r["W23"]) for r in rows)
        y = sum(len(r["W23"] - r[a]) for r in rows)
        L.append(f"- {names[a]} against W23 on upcoders found (descriptive): only {a} {x}, only W23 {y}.")
    if final:
        h1 = p_z(b, c) <= ALPHA and b > c
        g_ok = s("G_found") >= 0.9 * s("W23_found") and s("G_rounds") < s("W23_rounds")
        L += ["", "**Default for workflow v2.4 by the rule:** " + ("GL" if h2 else "L" if h1 else "G" if g_ok else "W23 stays (no variant passed)") + "."]
    return "\n".join(L)


if __name__ == "__main__":
    t = report(load())
    print(t)
    if "--write" in sys.argv:
        open(os.path.join(ROOT, "docs", "release4_results.md"), "w").write(t + "\n")
