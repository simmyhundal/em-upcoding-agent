"""Statistics of the data 4.0 development seeds for docs/data_v4_0.md (issue 124), pooled over the seeds built by eval/make_d4_dev.py. Free. Writes docs/data_v4_0_stats.md.
Usage: python eval/data_v4_stats.py"""
import csv
import json
import os
import sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "eval"))
import dev_release3 as dev  # noqa: E402
import eval61_recovery as rec  # noqa: E402
import make_d4_dev as md  # noqa: E402
import records  # noqa: E402
import score_40 as s4  # noqa: E402

LV = {"99211": 0, "99212": 1, "99213": 2, "99214": 3, "99215": 4}
OUT = os.path.join(ROOT, "docs", "data_v4_0_stats.md")


def doc_level(u):
    return max(records.mdm_level(int(u["problems_level"]), int(u["data_level"]), int(u["risk_level"])), records.level_from_minutes(u["documented_minutes"]))


def main():
    reading = defaultdict(Counter)
    rates = defaultdict(list)
    drift = defaultdict(lambda: [0, 0, 0, 0])
    listed = Counter()
    n_up = Counter()
    shared, nonmeans, realized_non = [], [], []
    seeds = [s for s in md.SEEDS if os.path.isdir(os.path.join(ROOT, "data", f"synthetic_v2_d4_{s}", "view"))]
    for s in seeds:
        code = f"d4_{s}"
        data = os.path.join(ROOT, "data", f"synthetic_v2_{code}")
        k = json.load(open(os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_{code}.json")))
        J, P = k["justified_cpt_by_claim"], k["providers"]
        claims = defaultdict(list)
        for r in csv.DictReader(open(os.path.join(data, "view", "claims.csv"))):
            claims[r["provider_id"]].append(r)
        uni = {r["claim_id"]: r for r in csv.DictReader(open(os.path.join(data, "records", "records_universe.csv")))}
        top = {r["provider_id"] for r in csv.DictReader(open(os.path.join(ROOT, "experiments", code, f"flagged_{dev.write_flagged(code, 'eb_ratio_t', 10)}.csv"))) if r["flagged"] == "True"}
        shared.append(k["members_seen_by_two_or_more_providers"])
        for pid, v in P.items():
            rows = claims[pid]
            t = s4.provider_truth(rows, J, rec.allowed())
            if v["role"] == "upcoder":
                hab = v["habit"] + (" (cloner)" if v["clones_notes"] else "")
                rates[hab].append(t["net_rate"])
                n_up[hab] += 1
                listed[hab] += pid in top
            else:
                nonmeans.append(v["mean_net_rate"])
                realized_non.append(t["net_rate"])
            for r in rows:
                b, j = LV[r["cpt"]], LV[J[r["claim_id"]]]
                grp = ("correctly billed" if b == j else ("downcoded" if b < j else ("honest noise, upcoded" if v["role"] != "upcoder" else v["habit"] + (" (cloner)" if v["clones_notes"] else "") + ", upcoded")))
                u = uni.get(r["claim_id"])
                if u is None:
                    continue
                d = doc_level(u)
                reading[grp]["higher" if d > b else ("as billed" if d == b else "lower")] += 1
                if v["role"] == "upcoder" and b > j:
                    late = r["service_date"] >= "2024-07-01"
                    h = drift[v["habit"]]
                    h[0] += late
                    h[1] += 1
            if v["role"] == "upcoder":
                h = drift[v["habit"]]
                h[2] += sum(r["service_date"] >= "2024-07-01" for r in rows)
                h[3] += len(rows)
    L = ["# Data 4.0 development seeds: what the generator produced", "", "[Back to the README](../README.md) · [data 4.0](data_v4_0.md)", "",
         f"Generated by `python eval/data_v4_stats.py`. Free. {len(seeds)} development seeds ({', '.join(map(str, seeds))}), each 216 providers, 8 planted upcoders, 8 hard negatives. Rates are net (billed above minus below the justified level) "
         "on the live claims the detector view keeps, computed with score 4.0's truth function.", "",
         "## Upcoders", "", "| Habit | Upcoders | Net rate: min / mean / max | In the eb_ratio_t top 10% list |", "|---|---|---|---|"]
    for h in sorted(rates):
        r = rates[h]
        L.append(f"| {h} | {n_up[h]} | {min(r):.0%} / {sum(r) / len(r):.0%} / {max(r):.0%} | {listed[h]} of {n_up[h]} |")
    tot_listed, tot_up = sum(listed.values()), sum(n_up.values())
    L += ["", f"The frozen screen (`eb_ratio_t`, a 99215-share ratio) lists {tot_listed} of {tot_up} upcoders in its top 10%: most habits do not move the 99215 share, which is the point of issue #127.", "",
          f"Non-upcoders: drawn mean net rate from {min(nonmeans):.0%} to {max(nonmeans):.0%}; realized on live claims from {min(realized_non):.0%} to {max(realized_non):.0%}. "
          f"Members seen by two or more providers: {sum(shared) / len(shared):.0%} (data 2.2: about 10% of visits were guest visits).", "",
          "## What a returned chart shows", "", "How the chart reads (the supported level by the decision-making or time rule, as the arms read it) against the billed level, over every visit of the development seeds.", "",
          "| Visits | Count | Chart shows the upcoding (reads lower than billed) | Reads as billed | Reads higher than billed |", "|---|---|---|---|---|"]
    for g in ("systematic, upcoded", "opportunistic, upcoded", "opportunistic (cloner), upcoded", "systematic (cloner), upcoded", "template, upcoded", "honest noise, upcoded", "correctly billed", "downcoded"):
        c = reading.get(g)
        if not c:
            continue
        n = sum(c.values())
        L.append(f"| {g} | {n:,} | {c['lower'] / n:.0%} | {c['as billed'] / n:.0%} | {c['higher'] / n:.0%} |")
    L += ["", "Correctly billed visits whose chart reads higher than billed are the reviewer-disagreement rate: with netting on, score 4.0 counts them as underpayments.", "",
          "## Drift over the year", "", "Share of an upcoder's upcoded visits dated in the second half of 2024, against the share of all its visits in that half.", "", "| Habit | Upcoded visits in H2 | All visits in H2 |", "|---|---|---|"]
    for h, (a, b, c_, d_) in sorted(drift.items()):
        L.append(f"| {h} | {a / max(b, 1):.0%} | {c_ / max(d_, 1):.0%} |")
    open(OUT, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
