"""Release 2: which upcoders did each arm miss, and where in the pipeline did they drop out? Free (stored runs and the answer key).

Funnel per planted upcoder (10 seeds, 78): (1) is it in the screen's top 5%, (2) did the arm ask for its records, (3) did the final summary call it
upcoding. Misses are then split by kind (cloned notes, subtle, true rate band, group billing, volume) and, for providers asked but not called, by the
leaning and the reason given. Writes docs/release2_misses.md. The answer key is used only here, after the runs.
"""
import csv
import json
import os
import re
import sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEEDS = [1515, 1616, 1717, 1818, 1919, 2020, 2121, 2222, 2323, 2424]


def asked(rid):
    out = set()
    p = os.path.join(ROOT, "experiments", rid, "office_transcript.jsonl")
    if os.path.exists(p):
        for line in open(p):
            e = json.loads(line)
            if e.get("action") in ("send_request", "follow_up") and "error" not in e:
                out.add(e["provider_id"])
    return out


def charts(rid):
    out = defaultdict(int)
    p = os.path.join(ROOT, "experiments", rid, "office_transcript.jsonl")
    if os.path.exists(p):
        for line in open(p):
            e = json.loads(line)
            if e.get("action") in ("send_request", "follow_up") and "error" not in e:
                out[e["provider_id"]] += len(e.get("usable_claim_ids", []))
    return out


def summaries(rid):
    d = {}
    for x in map(json.loads, open(os.path.join(ROOT, "experiments", rid, "case_summaries_checked.jsonl"))):
        d[x["provider_id"]] = x
    return d


def band(r):
    return "under 15%" if r < 0.15 else ("15 to 25%" if r < 0.25 else "25% and over")


def main():
    rows = []
    for seed in SEEDS:
        key = json.load(open(os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_r2_{seed}.json")))["providers"]
        shown = {r["provider_id"]: r for r in csv.DictReader(open(os.path.join(ROOT, "experiments", f"r2w_{seed}", "flagged_eb_ratio_top5pct.csv")))
                 if r["flagged"] == "True"}
        ranks = {r["provider_id"]: r["rank"] for r in csv.DictReader(open(os.path.join(ROOT, "experiments", f"r2w_{seed}", "flagged_eb_ratio_top5pct.csv")))}
        claims = Counter(r["provider_id"] for r in csv.DictReader(open(os.path.join(ROOT, "data", f"synthetic_v2_r2_{seed}", "view", "claims.csv"))))
        arms = {}
        for arm, pre in (("W", "r2w"), ("A", "r2a")):
            rid = f"{pre}_{seed}"
            arms[arm] = {"asked": asked(rid), "sum": summaries(rid), "charts": charts(rid)}
        for pid, v in key.items():
            if v["role"] != "upcoder":
                continue
            row = {"seed": seed, "pid": pid, "clones": bool(v.get("clones_notes")), "subtle": bool(v.get("subtle")),
                   "rate": v["true_upcode_rate"], "group": str(v.get("billing_npi", "")).startswith("2"), "claims": claims[pid],
                   "screened": pid in shown, "rank": int(ranks[pid])}
            for arm in "WA":
                a = arms[arm]
                s = a["sum"].get(pid)
                row[arm + "_asked"] = pid in a["asked"]
                row[arm + "_charts"] = a["charts"].get(pid, 0)
                row[arm + "_lean"] = s["summary"]["leaning"] if s else None
                row[arm + "_called"] = bool(s and s["summary"]["leaning"] == "pattern_consistent_with_upcoding")
                row[arm + "_src"] = s.get("source") if s else None
            rows.append(row)
    return rows


def pct(a, b):
    return f"{a} of {b} ({a / b:.0%})" if b else "–"


def report(rows):
    n = len(rows)
    L = ["# Release 2: which upcoders were missed, and why", "", "[Back to the README](../README.md)", "",
         "Generated by `python eval/analyze_misses_release2.py` from the stored runs and the answer key (free). Ten seeds (1515 to 2424), 78 planted upcoders on data 2.2, "
         "screen `eb_ratio` top 5%, workflow v2.2 and agent v3.2 (Opus 5.5, low effort). Descriptive: it reads the same ten seeds the results came from, so "
         "reasons below are hypotheses to test on fresh seeds, not tuned fixes.", ""]
    scr = sum(r["screened"] for r in rows)
    L += ["## Summary", "",
          "- **Precision is not the weak number; recall is.** Of the doctors each arm called upcoding, 91% (workflow) and 92% (agent) were upcoders. Recall is 27% and 15%.",
          "- **The screen caps recall at 56%.** A top-5% list holds only about 11 doctors per seed, and 34 of the 78 upcoders sit just outside it (ranks 12 to 195; 21 of the 34 are at ranks 12 to 27). "
          "Neither arm asked for records on any of them. A wider list raises the ceiling (top 10%: 76%, top 15%: 85%) but sends more honest practices requests.",
          "- **Cloned notes are the biggest hole.** 23 cloned-notes upcoders were screened; the workflow called 4 and the agent 0. Cloning makes the charts match the bill, "
          "so documentation 'supports billing' and the rules stop at inconclusive, even when the share is far above expected. For honest-notes upcoders that were screened the "
          "workflow called 17 of 21 and the agent 12 of 21.",
          "- **Subtle upcoders are mostly never seen by the screen:** 15 of the 18 subtle ones are outside the top 5%. Their true rates are close to the 6-point line, which is the point of them.",
          "- **The agent is more cautious than the workflow once it has records:** it asked for records on 41 upcoders and called 12; the workflow asked on 44 and called 21. "
          "Its reasons were not read case by case here (open question for a follow-up).",
          "- **Everything above reads the same ten seeds the results came from.** These are hypotheses for fresh seeds, not changes to make and then call held out.", ""]
    L += ["## 1. Where upcoders drop out", "",
          "| Step | Count |", "|---|---|", f"| Planted upcoders | {n} |", f"| In the screen's top 5% | {pct(scr, n)} |"]
    for arm, name in (("W", "workflow v2.2"), ("A", "agent v3.2")):
        ask = sum(r[arm + "_asked"] for r in rows)
        askscr = sum(r[arm + "_asked"] and r["screened"] for r in rows)
        called = sum(r[arm + "_called"] for r in rows)
        L.append(f"| {name}: records requested | {pct(ask, n)}  (of those in the screen: {pct(askscr, scr)}) |")
        L.append(f"| {name}: called upcoding | {pct(called, n)}  (of those with records: {pct(called, ask)}) |")
    L += ["", "Reading the funnel: recall is the product of three leaks. The screen only lists 5% of doctors (about 11 of 216), the arm must then ask for records, and the "
          "summary must then call it.", ""]
    L += ["## 2. Who is missed, by kind of upcoder", "", "| Kind | Upcoders | In top 5% | Workflow found | Agent found |", "|---|---|---|---|---|"]
    def grp(label, pred):
        s = [r for r in rows if pred(r)]
        L.append(f"| {label} | {len(s)} | {pct(sum(r['screened'] for r in s), len(s))} | {pct(sum(r['W_called'] for r in s), len(s))} | {pct(sum(r['A_called'] for r in s), len(s))} |")
    grp("cloned notes", lambda r: r["clones"])
    grp("honest notes", lambda r: not r["clones"])
    for b in ("under 15%", "15 to 25%", "25% and over"):
        grp(f"true upcoding rate {b}", lambda r, b=b: band(r["rate"]) == b)
    grp("subtle (planted 8 to 12%)", lambda r: r["subtle"])
    grp("group-billed practice", lambda r: r["group"])
    grp("solo billing", lambda r: not r["group"])
    med = sorted(r["claims"] for r in rows)[len(rows) // 2]
    grp(f"fewer than {med} claims (below the median)", lambda r: r["claims"] < med)
    grp(f"{med} claims or more", lambda r: r["claims"] >= med)
    L += ["", "## 3. Upcoders the screen listed but the arm did not call", ""]
    for arm, name in (("W", "Workflow v2.2"), ("A", "Agent v3.2")):
        miss = [r for r in rows if r["screened"] and not r[arm + "_called"]]
        c = Counter((("records requested" if r[arm + "_asked"] else "never asked for records"), r[arm + "_lean"] or "no summary") for r in miss)
        L += [f"**{name}** ({len(miss)} of {scr} screened upcoders):", ""] + [f"- {k[0]}, final leaning `{k[1]}`: {v}" for k, v in c.most_common()] + [""]
        ch = [r[arm + "_charts"] for r in miss if r[arm + "_asked"]]
        if ch:
            L += [f"  Charts returned for those asked: median {sorted(ch)[len(ch) // 2]}, {sum(x < 8 for x in ch)} of {len(ch)} with fewer than 8.", ""]
    both = [r for r in rows if r["screened"] and r["W_called"] and not r["A_called"]]
    L += [f"Found by the workflow, missed by the agent (screened): {len(both)}; of those the agent never asked for records on {sum(not r['A_asked'] for r in both)} "
          f"and asked but did not call {sum(r['A_asked'] for r in both)}.", ""]
    sc_clone = [r for r in rows if r["screened"] and r["clones"]]
    sc_hon = [r for r in rows if r["screened"] and not r["clones"]]
    L += ["## 4. Screened upcoders: cloned notes against honest notes", "", "| Among upcoders in the top 5% | Count | Workflow called | Agent called |", "|---|---|---|---|"]
    for lab, g in (("cloned notes", sc_clone), ("honest notes", sc_hon)):
        L.append(f"| {lab} | {len(g)} | {pct(sum(r['W_called'] for r in g), len(g))} | {pct(sum(r['A_called'] for r in g), len(g))} |")
    why = Counter()
    for r in rows:
        if r["screened"] and r["W_asked"] and not r["W_called"]:
            sm = summaries(f"r2w_{r['seed']}")[r["pid"]]
            why[re.sub(r"\d+(\.\d+)?%?", "N", (sm.get("rule_reason") or "")).split(";")[0][:90]] += 1
    L += ["", "Why the workflow's rules left the asked-but-not-called providers inconclusive (rule reason, numbers masked):", ""]
    L += [f"- {v}: {k}" for k, v in why.most_common()]
    L += ["", "## 5. What the screen leaves out", "", "| Screen cutoff | Share of doctors | Planted upcoders inside |", "|---|---|---|"]
    for t, lab in ((11, "top 5% (used)"), (22, "top 10%"), (33, "top 15%"), (54, "top 25%")):
        L.append(f"| {lab} (rank {t} or better) | {t / 216:.0%} | {pct(sum(r['rank'] <= t for r in rows), n)} |")
    out = [r for r in rows if not r["screened"]]
    L += ["", f"The {len(out)} upcoders outside the top 5%: {sum(r['clones'] for r in out)} clone notes, {sum(r['subtle'] for r in out)} are subtle (planted 8 to 12%), "
          f"{sum(r['rate'] < 0.15 for r in out)} have a true rate under 15%. Neither arm requested records for any doctor outside the top 5%: "
          f"workflow {sum(r['W_asked'] for r in out)}, agent {sum(r['A_asked'] for r in out)} of {len(out)}.", ""]
    L += ["## 6. Per seed", "", "| Seed | Upcoders | In top 5% | Workflow | Agent |", "|---|---|---|---|---|"]
    for s in SEEDS:
        x = [r for r in rows if r["seed"] == s]
        L.append(f"| {s} | {len(x)} | {sum(r['screened'] for r in x)} | {sum(r['W_called'] for r in x)} | {sum(r['A_called'] for r in x)} |")
    return L


if __name__ == "__main__":
    rows = main()
    lines = report(rows)
    open(os.path.join(ROOT, "docs", "release2_misses.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))
