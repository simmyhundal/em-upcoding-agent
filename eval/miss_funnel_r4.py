"""Release 4 follow-up (issues for release 5): where do the upcoders GL (the v2.4 default) misses go, and why did the agent v3.4 find fewer than GL? Free (stored runs and the answer key).

Part 1, GL on the ten fresh seeds (3535 to 4444, 80 upcoders): each upcoder is placed at the first step where it drops out: not in the top-10% list; listed but skipped by the gate; asked but no usable
charts came back; asked with charts but the rules left it inconclusive (by reason); called. Part 2: the upcoders GL found and agent v3.4 did not, by cause. Writes docs/release4_misses.md.
"""
import csv
import json
import os
import re
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
import case_summary as cs  # noqa: E402
import summary_rules as sr  # noqa: E402

FRESH = [3535, 3636, 3737, 3838, 3939, 4040, 4141, 4242, 4343, 4444]
UP = "pattern_consistent_with_upcoding"


def summaries(rid):
    return {x["provider_id"]: x for x in map(json.loads, open(os.path.join(ROOT, "experiments", rid, "case_summaries_checked.jsonl")))}


def asked(rid):
    s = set()
    for line in open(os.path.join(ROOT, "experiments", rid, "office_transcript.jsonl")):
        e = json.loads(line)
        if e.get("action") in ("send_request", "follow_up", "audit_trail") and "error" not in e:
            s.add(e["provider_id"])
    return s


def mask(t):
    return re.sub(r"\d+(\.\d+)?%?", "N", t or "")[:90]


def main():
    funnel, reasons, both = Counter(), Counter(), Counter()
    for sd in FRESH:
        key = json.load(open(os.path.join(ROOT, "eval", "answer_key", f"ground_truth_v2_r4_{sd}.json")))["providers"]
        allrows = {r["provider_id"]: r for r in csv.DictReader(open(os.path.join(ROOT, "experiments", f"r4_{sd}", "flagged_eb_ratio_t_10.csv")))}
        gl, ag = summaries(f"r4gl_{sd}"), summaries(f"r4a_{sd}")
        gla = asked(f"r4gl_{sd}")
        data = os.path.join(ROOT, "data", f"synthetic_v2_r4_{sd}")
        packs = {o["provider_id"]: o["packet"] for o in cs.run(os.path.join(data, f"view_r4a_{sd}"), os.path.join(ROOT, "experiments", f"r4_{sd}", "flagged_eb_ratio_t_10.csv"),
                                                              "/tmp/m.jsonl", dry_run=True, rules="2.3")}
        for p, v in key.items():
            if v["role"] != "upcoder":
                continue
            r = allrows[p]
            kind = "cloned notes" if v.get("clones_notes") else "honest notes"
            if r["flagged"] != "True":
                funnel[("not in the top-10% list", kind)] += 1
            elif p not in gla:
                funnel[("listed, skipped by the gate", kind)] += 1
            elif gl[p]["summary"]["leaning"] == UP:
                funnel[("called", kind)] += 1
            else:
                n = (gl[p]["summary"].get("rationale") or "")
                nodocs = "only 0 documented" in (gl[p].get("rule_reason") or "")
                funnel[("asked, no usable charts came back" if nodocs else "asked, charts back, rules left it inconclusive", kind)] += 1
                if not nodocs:
                    reasons[mask(gl[p].get("rule_reason"))] += 1
            gl_up = p in gl and gl[p]["summary"]["leaning"] == UP
            ag_up = p in ag and ag[p]["summary"]["leaning"] == UP
            if gl_up and not ag_up:
                if p not in ag:
                    both["never asked by the agent"] += 1
                else:
                    lean, _ = sr.rule_leaning_23(packs[p])
                    docs = (packs[p].get("documentation_review") or {}).get("claims_with_documentation", 0)
                    both["asked, no usable charts came back" if docs == 0 else "asked, charts back, rules 2.3 on the agent's records say upcoding but it wrote inconclusive" if lean == UP
                         else "asked, charts back, evidence below the rules' thresholds (agent did not escalate as GL did)"] += 1
            if ag_up and not gl_up:
                both["found by the agent only"] += 1
    L = ["# Release 4: where upcoders are missed, and why agent v3.4 found fewer than GL", "", "[Back to the README](../README.md)", "",
         "Generated by `python eval/miss_funnel_r4.py`. Free. Fresh seeds 3535 to 4444, 80 upcoders. These seeds are development data for release 5 from here on.", "",
         "## 1. Where GL (the v2.4 default) loses upcoders", "", "| Step where the upcoder drops out | Cloned notes | Honest notes | Total |", "|---|---|---|---|"]
    steps = ["not in the top-10% list", "listed, skipped by the gate", "asked, no usable charts came back", "asked, charts back, rules left it inconclusive", "called"]
    for s in steps:
        a, b = funnel[(s, "cloned notes")], funnel[(s, "honest notes")]
        L.append(f"| {s} | {a} | {b} | {a + b} |")
    L += ["", "Reasons the rules left asked-with-charts upcoders inconclusive (numbers masked):", ""] + [f"- {n}: {t}" for t, n in reasons.most_common()]
    L += ["", "## 2. Why agent v3.4 found fewer upcoders than GL", "", "Upcoders GL called and the agent did not, by cause:", ""] + [f"- {n}: {t}" for t, n in both.most_common()]
    open(os.path.join(ROOT, "docs", "release4_misses.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
