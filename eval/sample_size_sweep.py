"""Write docs/sample_size_sweep.md from the saved sweep outputs (never typed by hand).

Rules rows come from experiments/sample_size_sweep/rules.json (two seeds). AI rows come from the AI runs on seed 42:
261012_8_api (30 charts per provider) and 261012_15..18_api (10, 20, 60, 100). Needs the answer key (gitignored).

Usage:
    python eval/sample_size_sweep.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AI_RUNS = {10: "261012_15_api", 20: "261012_16_api", 30: "261012_8_api", 60: "261012_17_api", 100: "261012_18_api"}
KEY = os.path.join(ROOT, "eval", "answer_key", "ground_truth_v2_261012_1_code.json")


def usd(rid):
    tot = 0.0
    for f in ("usage_writer.jsonl", "usage_judge.jsonl"):
        path = os.path.join(ROOT, "experiments", rid, f)
        if os.path.exists(path):
            tot += sum(json.loads(line)["estimated_usd"] for line in open(path))
    return tot


def main():
    rules = json.load(open(os.path.join(ROOT, "experiments", "sample_size_sweep", "rules.json")))
    truth = json.load(open(KEY))["providers"]
    sizes = sorted(AI_RUNS)
    lines = ["# Records request sample size: what changes", "",
             "How many charts a plan requests per flagged provider (the response model is the same as the main runs: 80% respond, "
             "late ones are discarded). Upcoders: 8 per dataset. Generated by `python eval/sample_size_sweep.py`; the rules sweep is "
             "built by `eval/make_v2_sample_sweep.py` and the AI runs by `eval/make_v2_ai_runs.py`.", "",
             "## Chart rules (no AI), two seeds",
             "Found / honest accused among the flagged providers, by charts requested per provider.", "",
             "| Charts requested | Usable charts back (seed 42, per provider) | Documented below billed: seed 42 | seed 101 | "
             "Data without tests: seed 42 | seed 101 |", "|---|---|---|---|---|---|"]
    for n in sizes:
        a, b = rules[f"seed 42|{n}"], rules[f"seed 101|{n}"]
        cell = lambda r, k: f"{r['rules'][k]['upcoders']} found / {r['rules'][k]['honest']} honest"
        lines.append(f"| {n} | {a['returned_per_provider']:.0f} | {cell(a, 'documented_below_billed')} | {cell(b, 'documented_below_billed')} "
                     f"| {cell(a, 'data_without_tests')} | {cell(b, 'data_without_tests')} |")
    lines += ["", "## The AI step, seed 42 (half the upcoders clone notes)",
              "The screen sends the same 13 doctors every time (6 of the 8 upcoders, 7 honest). Only the records request changes.", "",
              "| Charts requested | Upcoders called | Honest doctors accused | Summaries written by rules / model | Usefulness | Estimated cost |",
              "|---|---|---|---|---|---|"]
    for n in sizes:
        rid = AI_RUNS[n]
        recs = [json.loads(line) for line in open(os.path.join(ROOT, "experiments", rid, "case_summaries_checked.jsonl"))]
        calls = [r for r in recs if r["summary"]["leaning"] == "pattern_consistent_with_upcoding"]
        up = sum(truth[r["provider_id"]]["role"] == "upcoder" for r in calls)
        src = [sum(r["source"] == k for r in recs) for k in ("rules", "llm")]
        use = [json.loads(line)["score"] for line in open(os.path.join(ROOT, "experiments", rid, "usefulness.jsonl"))]
        lines.append(f"| {n} | {up} of 8 | {len(calls) - up} | {src[0]} / {src[1]} | {sum(use) / len(use):.2f} | ${usd(rid):.2f} |")
    lines += ["", "Read with care: 8 upcoders per dataset, so one doctor moves a rate by 12.5 points; the AI sweep is one seed; and the response "
              "model (80% respond, 10 to 60 days) is an assumption."]
    open(os.path.join(ROOT, "docs", "sample_size_sweep.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
